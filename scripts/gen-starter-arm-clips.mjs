import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { starterArmClipsPack } from '../src/commons/packs/arms/pack.ts';

/** Emit only literal alias data, preserving the existing native and rendered rig consumers. */
export function starterArmClipsTableSource() {
  const entry = starterArmClipsPack({ credit: 'Wildshard', licence: 'First-party' }).entries.at(0);
  if (entry === undefined) throw new Error('Arm clip pack has no aliases');
  const json = new TextDecoder().decode(entry.bytes);
  return `// Generated by scripts/gen-starter-arm-clips.mjs from the commons arms pack; DO NOT EDIT.\nexport const STARTER_ARM_CLIPS = ${json} as const;\n`;
}

/** Generate before rig producers and on ordinary Vite boot-table builds; no commons code enters runtime. */
export function genStarterArmClips(root = process.cwd()) {
  const output = resolve(root, 'src/game/systems/viewmodel/clips.generated.ts'), source = starterArmClipsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
