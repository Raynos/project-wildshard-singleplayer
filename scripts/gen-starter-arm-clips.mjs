import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import aliases from '../src/game/systems/viewmodel/armAliases.json' with { type: 'json' };

/** Emit only literal alias data, preserving the existing native and rendered rig consumers. */
export function starterArmClipsTableSource() {
  const json = JSON.stringify(aliases);
  return `// Generated by scripts/gen-starter-arm-clips.mjs from src/game/systems/viewmodel/armAliases.json; DO NOT EDIT.\nexport const STARTER_ARM_CLIPS = ${json} as const;\n`;
}

/** Generate before rig producers and on ordinary Vite boot-table builds. */
export function genStarterArmClips(root = process.cwd()) {
  const output = resolve(root, 'src/game/systems/viewmodel/clips.generated.ts'), source = starterArmClipsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
