// GR0: generated products leave src; existing exact paths only burn down.
import { execFileSync } from 'node:child_process';
import { closeSync, existsSync, lstatSync, openSync, readFileSync, readSync, readdirSync } from 'node:fs';
import { posix, resolve } from 'node:path';

export const GENERATED_SOURCE_POLICY = 'lint/generated-source-debt.json';
const SOURCE_EXEMPTIONS = 'lint/generated-import-debt.json';
const CATALOGUES = ['scripts/generation-jobs.json', 'scripts/source-generation-outputs.json'];
/** @typedef {{schema:'generated-source/1',source:string,files:string[]}} SourcePolicy */
/** @typedef {Map<string,{mode:string,oid:string}>} GitTree */

/** @param {string} file */
function inSource(file) { return file.startsWith('src/') && !file.split('/').includes('node_modules'); }
/** @param {string} file */
function sourcePath(file) {
  return inSource(file) && file.length > 4 && !file.endsWith('/') && file === posix.normalize(file)
    && !/[\\\0\r\n*?[\]]/u.test(file);
}
/** @param {unknown} value @param {string} label @returns {string[]} */
function strings(value, label) {
  if (!Array.isArray(value)) throw new Error(`GENERATED-SOURCE ${label}: expected paths`);
  return value.map((/** @type {unknown} */ item) => {
    if (typeof item !== 'string') throw new Error(`GENERATED-SOURCE ${label}: invalid path`);
    return item;
  });
}
/** @param {unknown} value @returns {SourcePolicy} */
export function generatedSourcePolicy(value) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) throw new Error('GENERATED-SOURCE invalid policy');
  const schema = Reflect.get(value, 'schema'), source = Reflect.get(value, 'source');
  const files = strings(Reflect.get(value, 'files'), GENERATED_SOURCE_POLICY);
  if (schema !== 'generated-source/1' || typeof source !== 'string' || !/^[a-f0-9]{40}$/u.test(source)
    || Object.keys(value).sort().join(',') !== 'files,schema,source' || new Set(files).size !== files.length
    || files.some(file => !sourcePath(file))) throw new Error(`GENERATED-SOURCE ${GENERATED_SOURCE_POLICY}: invalid policy`);
  return { schema, source, files };
}
/** @param {SourcePolicy} before @param {SourcePolicy} after */
export function generatedSourceIncreases(before, after) {
  const allowed = new Set(before.files);
  return after.files.filter(file => !allowed.has(file)).map(file => `GENERATED-SOURCE ${GENERATED_SOURCE_POLICY}: allowance grew for ${file}`);
}
/** @param {(file:string)=>string|undefined} read */
function exemptSources(read) {
  const text = read(SOURCE_EXEMPTIONS);
  if (text === undefined) return new Set();
  const value = JSON.parse(text);
  const files = strings(value.sources ?? [], SOURCE_EXEMPTIONS);
  if (files.some(file => !sourcePath(file))) throw new Error(`GENERATED-SOURCE ${SOURCE_EXEMPTIONS}: invalid app sources`);
  return new Set(files);
}
/** @param {(file:string)=>string|undefined} read */
function declaredOutputs(read) {
  const found = new Set();
  for (const file of CATALOGUES) {
    const text = read(file); if (text === undefined) continue;
    const value = JSON.parse(text);
    const rows = file.endsWith('generation-jobs.json') ? value.jobs.map((/** @type {{outputs:unknown}} */ row) => row.outputs) : Object.values(value.producers);
    for (const row of rows) for (const output of strings(row, file)) {
      if (!output.startsWith('src/')) continue;
      if (!sourcePath(output)) throw new Error(`GENERATED-SOURCE ${file}: invalid output ${output}`);
      found.add(output);
    }
  }
  return found;
}
/** @param {string} file @param {string} [header] */
function marked(file, header = '') {
  return /\.generated(?:\.|$)/u.test(file) || /^src\/shards\/[^/]+\/assets\/[a-f0-9]{64}$/u.test(file)
    || /^\s*(?:\/\/|\/\*)[^\n]*(?:@generated|auto-generated|autogenerated|Generated by\b|DO[- ]NOT[- ]EDIT)/imu.test(header);
}
/** @param {string} file */
function readHeader(file) {
  const opened = openSync(file, 'r'), bytes = Buffer.alloc(512);
  try { return bytes.subarray(0, readSync(opened, bytes, 0, bytes.length, 0)).toString(); }
  finally { closeSync(opened); }
}
/** @param {Iterable<string>} outputs @param {SourcePolicy} policy @param {Set<string>} exempt */
function failures(outputs, policy, exempt) {
  const allowed = new Set(policy.files);
  return [...outputs].filter(file => !allowed.has(file) && !exempt.has(file)).sort()
    .map(file => `GENERATED-SOURCE ${file}: new generated file under src; return rows or bytes to the build instead`);
}
/** @param {string} root @param {string[]} args @param {Buffer} [input] */
function git(root, args, input) { return execFileSync('git', args, { cwd: root, input, maxBuffer: 256 * 1024 * 1024, stdio: ['pipe', 'pipe', 'pipe'] }); }
/** @param {string} root @param {string} revision @returns {GitTree} */
function entries(root, revision) {
  const raw = git(root, revision === ':' ? ['ls-files', '--stage', '-z'] : ['ls-tree', '-rz', revision]), tree = new Map();
  for (const record of raw.toString().split('\0').filter(Boolean)) {
    const tab = record.indexOf('\t'), [mode, middle, last] = record.slice(0, tab).split(' ');
    if (tab === -1 || mode === undefined || middle === undefined || last === undefined || (revision === ':' && last !== '0'))
      throw new Error('GENERATED-SOURCE malformed Git inventory');
    tree.set(record.slice(tab + 1), { mode, oid: revision === ':' ? middle : last });
  }
  return tree;
}
/** @param {string} root @param {GitTree} tree @param {string} file */
function readBlob(root, tree, file) {
  const row = tree.get(file); if (row === undefined) return undefined;
  if (row.mode !== '100644' && row.mode !== '100755') throw new Error(`GENERATED-SOURCE ${file}: non-regular policy input`);
  return git(root, ['cat-file', 'blob', row.oid]).toString();
}
/** @type {Map<string,string[]>} */
const publishedPolicies = new Map();
/** A rollback can restore an exact allowance present on published main in the
 * last day. Unpublished ancestors and older removed allowances grant nothing.
 * @param {string} root @param {string} previous @param {string} file
 * @param {string} schema @param {string} path
 * @param {number|true|{base64Chars:number,dataUris:number}} expected */
export function publishedPolicyRestoration(root, previous, file, schema, path, expected) {
  let published;
  try { published = git(root, ['merge-base', previous, 'refs/remotes/origin/main']).toString().trim(); }
  catch { return false; }
  const key = `${root}\0${published}\0${file}`;
  let snapshots = publishedPolicies.get(key);
  if (snapshots === undefined) {
    snapshots = [];
    try {
      const rows = git(root, ['log', '--first-parent', '--since=24 hours ago', '--format=%H %P', published, '--', file]).toString().trim();
      // A value removed today may have been introduced long ago; its removal's
      // first parent still proves that value existed inside the same window.
      const revisions = new Set(rows.split('\n').filter(Boolean).flatMap(row => row.split(' ').slice(0, 2)));
      for (const revision of revisions) {
        try { snapshots.push(git(root, ['show', `${revision}:${file}`]).toString()); }
        catch { /* A missing historical policy grants no allowance. */ }
      }
    } catch { /* Without readable published history, ordinary strict comparison applies. */ }
    publishedPolicies.set(key, snapshots);
  }
  return snapshots.some(text => {
    try {
      const value = JSON.parse(text);
      if (value?.schema !== schema || typeof value.source !== 'string' || !/^[a-f0-9]{40}$/u.test(value.source)) return false;
      const files = value.files;
      if (expected === true) return generatedSourcePolicy(value).files.includes(path);
      if (files === null || typeof files !== 'object' || Array.isArray(files) || !Object.hasOwn(files, path)) return false;
      const prior = files[path];
      return typeof expected === 'number' ? prior === expected
        : prior !== null && typeof prior === 'object' && !Array.isArray(prior)
          && Object.keys(prior).sort().join(',') === 'base64Chars,dataUris'
          && prior.base64Chars === expected.base64Chars && prior.dataUris === expected.dataUris;
    } catch { return false; }
  });
}
/** Exact staged/committed declarations and source bytes; dirty files cannot hide or invent a failure.
 * @param {string} root @param {string} revision @param {string} previous @param {readonly string[]} changed */
export function checkGeneratedSourceRevision(root, revision, previous, changed) {
  const tree = entries(root, revision), parent = entries(root, previous);
  if (!tree.has(GENERATED_SOURCE_POLICY)) return parent.has(GENERATED_SOURCE_POLICY)
    ? [`GENERATED-SOURCE ${GENERATED_SOURCE_POLICY}: policy deleted`] : [];
  const read = (/** @type {string} */ file) => readBlob(root, tree, file);
  const after = generatedSourcePolicy(JSON.parse(read(GENERATED_SOURCE_POLICY) ?? 'null'));
  const prior = readBlob(root, parent, GENERATED_SOURCE_POLICY);
  const before = prior === undefined ? undefined : generatedSourcePolicy(JSON.parse(prior));
  const restored = after.files.filter(file => !before?.files.includes(file)
    && publishedPolicyRestoration(root, previous, GENERATED_SOURCE_POLICY, after.schema, file, true));
  const errors = before === undefined ? [] : generatedSourceIncreases({ ...before, files: [...before.files, ...restored] }, after);
  const outputs = new Set([...declaredOutputs(read)].filter(file => tree.has(file) && changed.includes(file)));
  for (const file of changed) if (tree.has(file) && inSource(file) && marked(file)) outputs.add(file);
  for (const file of changed) if (inSource(file) && tree.has(file) && /\.[cm]?[jt]sx?$/u.test(file)
    && marked(file, (read(file) ?? '').slice(0, 512))) outputs.add(file);
  return [...errors, ...failures(outputs, after, exemptSources(read))];
}
/** The completed build tree includes ignored files. A sealed mirror's tracked manifest replaces Git discovery.
 * Dependency installations are not source outputs and are never walked.
 * @param {string} root */
export function generatedSourceFiles(root) {
  const read = (/** @type {string} */ file) => existsSync(resolve(root, file)) ? readFileSync(resolve(root, file), 'utf8') : undefined;
  const outputs = declaredOutputs(read), manifest = read('.push-tracked.json');
  const tracked = manifest === undefined ? null : new Set(strings(JSON.parse(manifest), '.push-tracked.json'));
  const visit = (/** @type {string} */ directory) => {
    if (!existsSync(resolve(root, directory))) return;
    for (const entry of readdirSync(resolve(root, directory), { withFileTypes: true })) {
      if (entry.name === 'node_modules') continue;
      const file = `${directory}/${entry.name}`;
      if (entry.isDirectory()) visit(file);
      else if (entry.isFile() && (marked(file) || tracked?.has(file) === false
        || (/\.[cm]?[jt]sx?$/u.test(file) && marked(file, readHeader(resolve(root, file)))))) outputs.add(file);
    }
  };
  visit('src');
  if (tracked === null && existsSync(resolve(root, '.git'))) {
    const ignored = git(root, ['ls-files', '--others', '--ignored', '--exclude-standard', '-z', '--', 'src']).toString().split('\0');
    for (const file of ignored) if (inSource(file)) outputs.add(file);
  }
  return [...outputs].sort((a, b) => a.localeCompare(b));
}
/** Post-generation check: no ignored or newly declared src output gets an implicit allowance.
 * @param {string} root */
export function checkGeneratedSourceTree(root) {
  const policyFile = resolve(root, GENERATED_SOURCE_POLICY);
  // Historical projects/fixtures predate this repository policy. Once present,
  // its deletion is refused by the immutable revision check above.
  if (!existsSync(policyFile)) return [];
  if (lstatSync(policyFile).isSymbolicLink()) throw new Error(`GENERATED-SOURCE ${GENERATED_SOURCE_POLICY}: symlink policy`);
  const policy = generatedSourcePolicy(JSON.parse(readFileSync(policyFile, 'utf8')));
  const read = (/** @type {string} */ file) => existsSync(resolve(root, file)) ? readFileSync(resolve(root, file), 'utf8') : undefined;
  return failures(generatedSourceFiles(root), policy, exemptSources(read));
}
