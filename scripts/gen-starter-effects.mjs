import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { starterEffectsPack } from '../src/commons/packs/effects/pack.ts';

/** Build-only pack expansion; boot imports this literal table and never commons code. */
export function starterEffectsTableSource() {
  const entry = starterEffectsPack({ credit: 'Wildshard', licence: 'First-party' }).entries.at(0);
  if (entry === undefined) throw new Error('Starter effects pack has no rows');
  const json = new TextDecoder().decode(entry.bytes);
  return `// Generated by scripts/gen-starter-effects.mjs from the commons effects pack; do not edit.\nexport const STARTER_EFFECT_ROWS = ${json} as const;\n`;
}
/** Generate on every normal build, clean export and test setup through pnpm gen. */
export function genStarterEffects(root = process.cwd()) {
  const output = resolve(root, 'src/game/systems/effects/starter.generated.ts'), source = starterEffectsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
