import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import rows from '../src/game/systems/effects/starterRows.json' with { type: 'json' };

/** Build-only expansion of the authored status rows; boot imports this literal table. */
export function starterEffectsTableSource() {
  const json = JSON.stringify(rows);
  return `// Generated by scripts/gen-starter-effects.mjs from src/game/systems/effects/starterRows.json; do not edit.\nexport const STARTER_EFFECT_ROWS = ${json} as const;\n`;
}
/** Generate on every normal build, clean export and test setup through pnpm gen. */
export function genStarterEffects(root = process.cwd()) {
  const output = resolve(root, 'src/game/systems/effects/starter.generated.ts'), source = starterEffectsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
