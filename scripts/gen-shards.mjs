// E357 F9: folder discovery is the sole authored shard list.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export function shardFolders(root) {
  return readdirSync(resolve(root, 'src/shards'), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(resolve(root, 'src/shards', entry.name, 'manifest.ts')))
    .map((entry) => entry.name).sort();
}

export function shardSource(root) {
  const slugs = shardFolders(root);
  if (slugs.length === 0) throw new Error('gen-shards: no shard manifests');
  return `// Generated by scripts/gen-shards.mjs — do not edit or commit.
import type { ShardManifest } from './manifest';
${slugs.map((slug, i) => `import m${i} from '#shards/${slug}/manifest';`).join('\n')}
export const SHARDS: readonly ShardManifest[] = [${slugs.map((_, i) => `m${i}`).join(', ')}].sort((a, b) => a.order - b.order);
export type ShardSlug = ${slugs.map((slug) => JSON.stringify(slug)).join(' | ')};
`;
}

export function genShards(root = resolve(import.meta.dirname, '..'), check = false) {
  const out = resolve(root, 'src/game/shard/shards.generated.ts');
  const source = shardSource(root);
  const same = existsSync(out) && readFileSync(out, 'utf8') === source;
  if (check && !same) throw new Error('gen-shards: stale src/game/shard/shards.generated.ts (run pnpm gen)');
  if (!check && !same) { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, source); }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { genShards(undefined, process.argv.includes('--check')); }
  catch (error) { console.error(error instanceof Error ? error.message : String(error)); process.exitCode = 1; }
}
