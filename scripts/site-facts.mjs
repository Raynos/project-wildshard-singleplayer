#!/usr/bin/env node
// The marketing site's facts (P1-W1, E506 RD14): every number and excerpt site/ shows about the game, read from the
// game's own sources and published as one JSON, so the site reads that file and nothing else of this repo.
//   node scripts/site-facts.mjs                    writes site/facts.json (committed: the site builds from it alone)
//   node scripts/site-facts.mjs --out <file>       writes <file> instead (`pnpm build` publishes dist/site-facts.json)
//   node scripts/site-facts.mjs --check            exits 1 when site/facts.json differs from the sources
//   --stale-warn <file>                            with --out: also warn (never fail) when <file> is stale
// Sources: the single-player grid (src/game/grid/singleplayer.json), the cell size and memory caps
// (@wildshard/format/contentBounds), the road width (@wildshard/engine/core/config), the shard.json schema's path count
// (@wildshard/format/shardSchema through scripts/docs/schema-reference.mjs) and an excerpt of the template's built
// shard.json (out/_template/shard.json: run node scripts/build-shardfiles.mjs first). The site formats the numbers.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
export const SITE_FACTS = resolve(root, 'site/facts.json');
const FORMAT = 'wildshard-site-facts/1';

/** @param {unknown} v @param {string} what @returns {Record<string, unknown>} */
function record(v, what) {
  if (typeof v !== 'object' || v === null || Array.isArray(v)) throw new Error(`site-facts: ${what} is not a JSON object`);
  return Object.fromEntries(Object.entries(v));
}
/** @param {unknown} v @param {string} what @returns {unknown[]} */
function list(v, what) { if (!Array.isArray(v)) throw new Error(`site-facts: ${what} is not a JSON array`); return v; }
/** @param {unknown} v @param {string} what @returns {number} */
function number(v, what) {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`site-facts: ${what} is not a number`);
  return v;
}
/** @param {string} file */
const json = (file) => record(JSON.parse(readFileSync(resolve(root, file), 'utf8')), file);

/** the one single-player grid used by public and Developer alike (G972); a later row for a cell replaces an earlier */
function grid() {
  const g = record(json('src/game/grid/singleplayer.json').grid, 'grid');
  /** @type {Map<string, {x:number, z:number, slug:string, plot:boolean}>} */
  const at = new Map();
  for (const row of list(g.cells, 'grid.cells')) {
    const r = record(row, 'a grid cell'), cell = list(r.cell, 'a grid cell'), slug = String(r.slug);
    const x = number(cell[0], 'cell x'), z = number(cell[1], 'cell z');
    at.set(`${x},${z}`, { x, z, slug, plot: slug.startsWith('open-plot-') });
  }
  return { pitch: number(g.pitch, 'grid.pitch'), cells: [...at.values()] };
}

/** the template's built shard.json, cut to the fields the site's shardfile peek shows (MS15) */
function shardfileExcerpt() {
  const file = 'out/_template/shard.json';
  if (!existsSync(resolve(root, file))) throw new Error(`site-facts: no ${file}; run node scripts/build-shardfiles.mjs first`);
  const index = json(file), requires = record(index.requires, 'requires'), admission = record(index.admission, 'admission');
  return {
    version: index.version, identity: index.identity, requires: { sdk: requires.sdk },
    authorCaps: admission.authorCaps, serverBudget: admission.serverBudget, runtime: index.runtime ?? null,
  };
}

/** every fact, in the published shape (numbers stay numbers; site/tools/facts.ts words them) */
export async function siteFacts() {
  await import('./sim-node-loader.mjs');
  const { CHUNK_SIZE, MEMORY_GATES } = await import('@wildshard/format/contentBounds');
  const { ROAD_WIDTH } = await import('@wildshard/engine/core/config');
  const { ShardfileSchema } = await import('@wildshard/format/shardSchema');
  const { schemaInventory } = await import('./docs/schema-reference.mjs');
  const { pitch, cells } = grid();
  return {
    $doc: 'Generated by scripts/site-facts.mjs (P1-W1) from the game\'s sources; do not edit. The site reads only this.',
    format: FORMAT,
    grid: { cellSize: CHUNK_SIZE, pitch, road: ROAD_WIDTH, cells },
    memory: { explorerMB: MEMORY_GATES.explorerMB, loadingMB: MEMORY_GATES.loadingMB },
    schemaPaths: schemaInventory(ShardfileSchema).length,
    shardfile: shardfileExcerpt(),
  };
}

/** @param {unknown} facts */
export const factsText = (facts) => `${JSON.stringify(facts, null, 2)}\n`;

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  /** @param {string} flag */
  const value = (flag) => { const i = args.indexOf(flag); return i === -1 ? undefined : args[i + 1]; };
  const text = factsText(await siteFacts());
  const out = resolve(value('--out') ?? SITE_FACTS);
  const stale = (/** @type {string} */ file) => !existsSync(file) || readFileSync(file, 'utf8') !== text;
  if (args.includes('--check')) {
    if (stale(SITE_FACTS)) {
      console.error('site-facts: site/facts.json is stale; run node scripts/site-facts.mjs and commit it');
      process.exit(1);
    }
    console.info('site-facts: site/facts.json is current');
  } else {
    writeFileSync(out, text);
    console.info(`site-facts: wrote ${out}`);
    const warn = value('--stale-warn');
    if (warn !== undefined && stale(resolve(warn))) {
      console.warn(`site-facts: ${warn} is stale; run node scripts/site-facts.mjs and commit it (the site builds from it)`);
    }
  }
}
