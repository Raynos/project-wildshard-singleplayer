// The encoder and the F9 migration share this partition; generation never needs basisu.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

/** @typedef {{phone:Record<string,string>,desktop:Record<string,string>}} Ktx2Map */
const ENGINE_INPUT = 'scripts/ktx2-engine-map.json';
const ENGINE_HEADER = '// Generated by gen:source (scripts/ktx2-tables.mjs) from scripts/ktx2-engine-map.json; commit with its KTX2 assets.\n';
const SHARD_HEADER = '// Generated by scripts/bake-ktx2.mjs — commit this table with its KTX2 assets.\n';
/** @param {unknown} value @returns {value is Record<string,unknown>} */
const record = value => typeof value === 'object' && value !== null && !Array.isArray(value);
/** The encoder's activated mappings are committed metadata, not cache keys or
 * an encode request. Generation never runs basisu or reads the output table.
 * @param {unknown} value @returns {Ktx2Map} */
function orderedTable(value) {
  if (!record(value) || Object.keys(value).sort().join('|') !== 'desktop|phone') throw new Error('KTX2 activation map needs exactly phone and desktop');
  /** @type {Ktx2Map} */
  const table = { phone: {}, desktop: {} };
  for (const tier of /** @type {const} */ (['phone', 'desktop'])) {
    const input = value[tier];
    if (!record(input)) throw new Error(`KTX2 activation map ${tier} must be a mapping`);
    for (const [source, target] of Object.entries(input).sort(([a], [b]) => a.localeCompare(b))) {
      if (source.length === 0 || typeof target !== 'string' || target.length === 0) throw new Error(`KTX2 activation map ${tier} needs nonempty string URLs`);
      table[tier][source] = target;
    }
  }
  return table;
}
/** @param {Ktx2Map} table @param {string} header */
function tableSource(table, header) {
  return `${header}export const GPU_FILES: { readonly phone: Readonly<Record<string, string>>; readonly desktop: Readonly<Record<string, string>> } = ${JSON.stringify(orderedTable(table), null, 2)};\n`;
}
/** Plain committed engine table from the encoder's exact activated map.
 * @param {string} root */
export function engineKtx2TableSource(root) {
  const table = orderedTable(JSON.parse(readFileSync(resolve(root, ENGINE_INPUT), 'utf8')));
  return tableSource(table, ENGINE_HEADER);
}

/** Default texture ownership roots; a shard's authored assetGlobs add to them. */
function defaultAssetGlobs(slug) {
  return [
    `public/assets/${slug}/**`,
    `public/assets/gpu/${slug}/**`,
    `public/assets/baked/${slug}/**`,
    `public/assets/gpu/baked/${slug}/**`,
    `public/assets/music/${slug}/**`,
    `public/assets/sfx/${slug}/**`,
    `public/assets/horizon/${slug}-*`,
    `public/assets/gpu/horizon/${slug}-*`,
    `public/assets/lut/${slug}.bin`,
    `public/assets/title/${slug}-portrait.jpg`,
  ];
}

const reCache = new Map();
/** A glob → RegExp: `**` any depth, `*` within one segment, `{a,b}` alternatives, everything else literal. */
function globToRegExp(glob) {
  const hit = reCache.get(glob);
  if (hit) return hit;
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') {
      i++;
      if (glob[i + 1] === '/') { i++; re += '(?:.*/)?'; } else re += '.*';
    } else if (c === '*') re += '[^/]*';
    else if (c === '?') re += '[^/]';
    else if (c === '{') re += '(?:';
    else if (c === '}') re += ')';
    else if (c === ',') re += '|';
    else re += c.replaceAll(/[.+^$()|[\]\\]/g, String.raw`\$&`);
  }
  const out = new RegExp(`^${re}$`);
  reCache.set(glob, out);
  return out;
}

export function splitKtx2(map, shards) {
  const tables = new Map([['engine', { phone: {}, desktop: {} }], ...shards.map((m) => [m.slug, { phone: {}, desktop: {} }])]);
  const owners = shards.map((m) => ({ slug: m.slug, patterns: [...defaultAssetGlobs(m.slug), ...(m.assetGlobs ?? [])].map(globToRegExp) }));
  for (const tier of ['phone', 'desktop']) for (const [url, target] of Object.entries(map[tier])) {
    // Procedural texture keys name CPU-generated pixels, not downloadable source images.
    const path = `public${url.replace(/^procedural:/u, '').split('#')[0]}`;
    const matches = owners.filter((owner) => owner.patterns.some((pattern) => pattern.test(path)));
    if (matches.length > 1) throw new Error(`KTX2 table has ambiguous ownership: ${url}`);
    tables.get(matches[0]?.slug ?? 'engine')[tier][url] = target;
  }
  return tables;
}

export function writeKtx2Tables(root, map, shards) {
  for (const [slug, table] of splitKtx2(map, shards)) {
    if (slug !== 'engine' && Object.keys(table.phone).length + Object.keys(table.desktop).length === 0) continue;
    const out = resolve(root, slug === 'engine' ? 'src/engine/boot/ktx2.generated.ts' : `src/shards/${slug}/ktx2.generated.ts`);
    if (slug === 'engine') {
      const input = resolve(root, ENGINE_INPUT), body = `${JSON.stringify(orderedTable(table), null, 2)}\n`;
      mkdirSync(dirname(input), { recursive: true });
      if (!existsSync(input) || readFileSync(input, 'utf8') !== body) writeFileSync(input, body);
    }
    const source = tableSource(table, slug === 'engine' ? ENGINE_HEADER : SHARD_HEADER);
    if (!existsSync(out) || readFileSync(out, 'utf8') !== source) writeFileSync(out, source);
  }
}
