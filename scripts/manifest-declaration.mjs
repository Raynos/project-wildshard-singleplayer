import { existsSync } from 'node:fs';
import { relative, resolve } from 'node:path';

/** Compile fixed discovery rows and their bundled images, without a runtime
 * image lookup or authored TypeScript list. Used by Nalati and Nine's existing
 * boot producers; the generated literal remains checked against ShardManifest. */
export function manifestDeclaration(root, slug, rows, omitted) {
  const images = new Map();
  const emit = value => {
    if (typeof value === 'string' && value.startsWith('/src/')) {
      if (!value.startsWith(`/src/shards/${slug}/`) || value.includes('..') || !/\.(jpe?g|png|webp|svg|hdr)$/u.test(value) || !existsSync(resolve(root, value.slice(1)))) throw new Error(`Invalid manifest image: ${value}`);
      if (!images.has(value)) images.set(value, `image${images.size}`);
      return images.get(value);
    }
    if (typeof value === 'number' && !Number.isFinite(value)) {
      if (value === Infinity) return 'Infinity';
      throw new Error('Invalid manifest number');
    }
    if (Array.isArray(value)) return `[${value.map(emit).join(',')}]`;
    if (value !== null && typeof value === 'object') return `{${Object.entries(value).map(([key, item]) => `${JSON.stringify(key)}:${emit(item)}`).join(',')}}`;
    if (typeof value === 'function' || typeof value === 'symbol' || typeof value === 'bigint' || value === undefined) throw new Error('Manifest declarations contain only fixed data');
    return JSON.stringify(value);
  };
  const { poses, ...fixed } = rows;
  const literal = emit(fixed);
  // Catalogue rows compile only native boot bindings; no authored callback body.
  const catalogue = fixed.audio?.catalogue === true;
  const declaration = catalogue ? `{...fixed, audio:{...fixed.audio,preload:async()=>(await import('@wildshard/game/shardfile/audioCatalogue')).productAudioCatalogue(${JSON.stringify(slug)})},boot:{...fixed.boot,audio:async()=>(await import('@wildshard/game/shardfile/audioCatalogue')).productAudioFiles(${JSON.stringify(slug)})}}` : literal;
  const capturePoses = poses === undefined ? '' : `export const POSES = ${emit(poses)} satisfies NonNullable<ShardManifestRows['poses']>;\n`;
  const folder = resolve(root, 'src/shards', slug, 'boot');
  return `// Generated by the shard boot metadata producer. Do not edit or commit.
import type { ShardManifest${poses === undefined ? '' : ', ShardManifestRows'} } from '@wildshard/game/shard/manifest';
${catalogue ? `const fixed = ${literal};` : ''}
${[...images].map(([path, name]) => `import ${name} from ${JSON.stringify(`./${relative(folder, resolve(root, path.slice(1)))}`)};`).join('\n')}
export const DECLARATION = ${declaration} satisfies Omit<ShardManifest, ${[...omitted, 'trees'].map(key => JSON.stringify(key)).join(' | ')}> & { trees: Partial<ShardManifest['trees']> };
${capturePoses}`;
}
