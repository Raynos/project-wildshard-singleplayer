#!/usr/bin/env node
// Trusted SF30 compiler: immutable admitted modules, never dynamic git operations.
// G348: the shards it bakes and what each compiles come from their own data (`src/shards/<slug>/data/moverBake.ts`,
// `MOVER_BAKE`, schema `@wildshard/format/movers` `MoverBakeSchema`), never a table here.
// node --experimental-transform-types --import ./scripts/bake-loader.mjs scripts/bake/movers.mjs [--shards=<slug>,…]
import { compileMoverDriver } from '../../src/sdk/compileMovers.ts';
import { moverBake } from '../../src/format/movers.ts';
import { existsSync, mkdirSync, readdirSync, writeFileSync, mkdtempSync, rmSync, symlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { build } from 'vite';

const repo = resolve(import.meta.dirname, '../..');
/** Every shard folder declaring a mover bake, sorted by folder name. */
const declared = [];
for (const slug of readdirSync(join(repo, 'src/shards')).sort()) {
  const file = join(repo, 'src/shards', slug, 'data/moverBake.ts');
  if (existsSync(file)) declared.push({ slug, bake: moverBake(slug, (await import(pathToFileURL(file).href)).MOVER_BAKE) });
}
const selected = process.argv.find(arg => arg.startsWith('--shards='))?.slice('--shards='.length).split(',') ?? declared.map(row => row.slug);
if (selected.some(slug => !declared.map(row => row.slug).includes(slug))) throw new Error('Unknown mover shard');
const shards = declared.filter(row => selected.includes(row.slug));
const hashes = new Map();
for (const { slug, bake } of shards) for (const module of bake.modules) {
  const bytes = await compileMoverDriver(module.driver);
  const hash = createHash('sha256').update(bytes).digest('hex'), directory = join(repo, 'src/shards', slug, 'assets');
  mkdirSync(directory, { recursive: true }); writeFileSync(join(directory, hash), bytes);
  hashes.set(`${slug}/${module.file}`, hash);
  process.stdout.write(`${slug}/${module.file} ${hash} ${bytes.length}\n`);
  // a module the shard's runtime admits by hash (Sky Reach's shardfile, SF8c socketLift / SF72) gets its data constant
  if (module.emit !== undefined) writeFileSync(join(repo, 'src/shards', slug, module.emit.file), `// Generated by scripts/bake/movers.mjs: ${module.emit.note}.\nexport const ${module.emit.name} = { hash: '${hash}', bytes: ${bytes.length} } as const;\n`);
}
const scratch = mkdtempSync(join(tmpdir(), 'mover-export-'));
try {
  symlinkSync(join(repo, 'node_modules'), join(scratch, 'node_modules'));
  for (const { slug, bake } of shards) {
    const directory = join(scratch, slug);
    await build({ configFile: false, logLevel: 'silent', build: { target: 'esnext', outDir: directory, emptyOutDir: true,
      lib: { entry: join(repo, 'src/shards', slug, 'generators/movers.ts'), formats: ['es'], fileName: 'capture' },
      rolldownOptions: { platform: 'node', external: [/^node:/u] } } });
    const capture = (await import(pathToFileURL(join(directory, 'capture.js')).href))[bake.capture];
    if (typeof capture !== 'function') throw new Error(`${slug}: generators/movers.ts has no ${bake.capture}`);
    const data = capture(...bake.modules.map(module => hashes.get(`${slug}/${module.file}`)));
    const target = join(repo, 'src/shards', slug, 'data'); mkdirSync(target, { recursive: true });
    writeFileSync(join(target, 'movers.ts'), `// Generated by scripts/bake/movers.mjs from today's collider/rest recipes.\nimport type { MoverData } from '@wildshard/sdk/movers';\n/** Admitted modules own fixed-step motion; the engine owns collision and the rope solver. */\nexport const MOVERS: MoverData = ${JSON.stringify(data, null, 2)};\n`);
  }
} finally { rmSync(scratch, { recursive: true, force: true }); }
