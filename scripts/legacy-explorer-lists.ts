const slugs = ['driftwood-isle', 'pine-hollow', 'nalati-grasslands', 'nine-dragon-stack', 'far-reach', 'sunscar-dunes'];
type Lists = Record<'models' | 'sets' | 'world' | 'arenas', string[] | null>;
interface Fields extends Record<string, unknown> { lists?: unknown; features?: unknown; kind?: unknown; rows?: unknown; manifest?: unknown; pois?: unknown; default?: unknown; course?: unknown; ROSTER?: unknown; shards?: unknown; shard?: unknown; shardfile?: unknown; inputs?: unknown }
interface Capture { lists: Lists; gaps: string[]; inputs: Record<string, string>; infrastructureWarnings: string[] }
const root = process.cwd();
const { WS_LD4_REVISION: inheritedRevision, WS_LD4_PRODUCT_DIRECTORY: inheritedProduct, WS_LD4_INDEX_HASH: inheritedIndex } = process.env;
const revision = inheritedRevision ?? execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (!/^[a-f0-9]{40}$/u.test(revision)) throw new Error('LD4 requires one exact committed public-asset revision');
const hash = (value: Uint8Array | string): string => createHash('sha256').update(value).digest('hex');
function object(value: unknown): Fields {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) throw new Error('Expected object');
  return value as Fields;
}
function rows(value: unknown): unknown[] { if (!Array.isArray(value)) throw new Error('Expected rows'); return value; }
function ids(value: unknown, key = 'id'): string[] {
  return rows(value).map(row => { const id = object(row)[key]; if (typeof id !== 'string') throw new Error(`Missing ${key}`); return id; });
}
function sorted(values: readonly string[]): string[] { return [...new Set(values)].sort((a, b) => a.localeCompare(b)); }

/** Historical generated bytes may be read only when their full content hash
 * is named by the committed catalogue. Verify the complete cache receipt and
 * every output; never use the loose public copy or claim fresh generation. */
function recordedGeneratedBytes(file: string, inputs: Record<string, string>): Uint8Array<ArrayBuffer> {
  const wanted = /-([a-f0-9]{64})(?:\.phone)?\.(?:glb|bin)$/u.exec(file)?.[1];
  if (wanted === undefined) throw new Error(`LD4 public asset is not a committed regular file: ${file}`);
  const source = execFileSync('git', ['show', `${revision}:scripts/generation-jobs.json`], { encoding: 'utf8' });
  const catalogue = v.parse(v.object({ jobs: v.array(v.object({ id: v.string(), outputs: v.array(v.string()) })) }), JSON.parse(source));
  const owners = catalogue.jobs.filter(job => job.outputs.includes(file)), job = owners[0];
  if (owners.length !== 1 || job === undefined || !/^[a-z0-9.-]+$/u.test(job.id)) throw new Error(`LD4 generated asset has no single committed producer: ${file}`);
  const base = resolve(generationCacheRoot(), job.id);
  const digest = v.pipe(v.string(), v.regex(/^[a-f0-9]{64}$/u));
  const Receipt = v.strictObject({ schema: v.literal('generation-cache/1'), key: digest, files: v.record(v.string(), digest) });
  for (const entry of readdirSync(base, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || !/^[a-f0-9]{64}$/u.test(entry.name)) continue;
    const directory = resolve(base, entry.name), release = borrowShardfileEntry(directory);
    try {
      // Both cache families use independent PID/24-hex files in .readers.
      // The existing lease excludes eviction, not a source freshness verdict.
      if (existsSync(`${directory}.lock`)) continue;
      const receipt = v.parse(Receipt, JSON.parse(readFileSync(resolve(directory, '.generation-receipt.json'), 'utf8')));
      if (receipt.key !== entry.name || receipt.files[file] !== wanted) continue;
      const actual = generationOutputHashes(directory, job.outputs);
      if (Object.keys(actual).length !== Object.keys(receipt.files).length || Object.entries(actual).some(([name, value]) => receipt.files[name] !== value)) continue;
      const bytes = Uint8Array.from(readFileSync(resolve(directory, file)));
      if (hash(bytes) !== wanted) throw new Error('LD4 generated bytes changed after receipt verification');
      inputs[`${revision}:scripts/generation-jobs.json`] = hash(source);
      inputs[`generation:${job.id}:${entry.name}:${file}`] = wanted;
      return bytes;
    } finally { release(); }
  }
  throw new Error(`Exact recorded generated bytes unavailable: ${file}`);
}

/** A Node-only HTTP byte capability. Read pinned Git objects, named product
 * payloads or catalogue-hash-pinned generated outputs; never loose files or
 * the network. Model readers retain their size/hash/decoder checks; this supplies no model definitions.
 * It exists only for this fresh audit child and is restored on every outcome. */
async function withPublicBytes<T>(inputs: Record<string, string>, read: () => Promise<T>, productFile: (url: string) => Promise<Uint8Array> | undefined): Promise<T> {
  const original = globalThis.fetch, origin = 'http://localhost';
  globalThis.fetch = (input, init) => {
    const request = input instanceof Request ? input : null;
    const url = new URL(request?.url ?? (input instanceof URL ? input.href : typeof input === 'string' ? input : input.url), origin);
    // GLTF-owned embedded buffers/images remain in memory; neither scheme
    // can fetch the network or read loose project files.
    if (url.protocol === 'blob:' || url.protocol === 'data:') return original(input, init);
    if ((init?.method ?? request?.method ?? 'GET') !== 'GET') throw new Error('LD4 asset reader accepts GETs only');
    const productBytes = productFile(url.href);
    if (productBytes !== undefined) return productBytes.then(bytes => new Response(Uint8Array.from(bytes), { headers: { 'content-length': String(bytes.length) } }));
    const source = url.protocol === 'file:' ? relative(root, fileURLToPath(url)).replaceAll('\\', '/') : null;
    if (source !== null && (isAbsolute(source) || source === '..' || source.startsWith('../'))) throw new Error('LD4 file URL escapes the repository');
    const file = source ?? (url.origin === origin && url.pathname.startsWith('/assets/') ? `public${url.pathname}`
      : url.origin === origin && url.pathname.startsWith('/src/') ? url.pathname.slice(1) : null);
    if (file === null || !file.startsWith('src/') && !file.startsWith('public/assets/')) throw new Error(`LD4 asset URL is outside source/public assets: ${url.href}`);
    const mode = execFileSync('git', ['ls-tree', revision, '--', file], { encoding: 'utf8' });
    const tracked = mode.startsWith('100644 blob ') || mode.startsWith('100755 blob ');
    const bytes = tracked ? execFileSync('git', ['show', `${revision}:${file}`], { maxBuffer: 64 * 1024 * 1024 }) : recordedGeneratedBytes(file, inputs);
    if (tracked) inputs[`${revision}:${file}`] = hash(bytes);
    return Promise.resolve(new Response(Uint8Array.from(bytes), { headers: { 'content-length': String(bytes.length), 'content-type': file.endsWith('.json') ? 'application/json' : 'application/octet-stream' } }));
  };
  try { return await read(); } finally { globalThis.fetch = original; }
}

/** Literal declarations are separate from runtime membership. Keep every
 * conditional/dynamic registration visible in the coverage gap below. */
function legacySets(slug: string, inputs: Record<string, string>): string[] {
  const files = execFileSync('git', ['ls-files', `src/shards/${slug}-legacy`], { encoding: 'utf8' }).trim().split('\n');
  const result: string[] = [];
  for (const file of files.filter(name => name.endsWith('.ts'))) {
    const source = readFileSync(file, 'utf8');
    if (!source.includes('placeSet(')) continue;
    inputs[file] = hash(source);
    const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const collect = (node: ts.Node): void => {
      if (ts.isObjectLiteralExpression(node)) {
        const properties = node.properties.filter(ts.isPropertyAssignment);
        const property = properties.find(row => row.name.getText(tree) === 'id') ?? properties.find(row => row.name.getText(tree) === 'place');
        if (property !== undefined && ts.isStringLiteral(property.initializer) && property.initializer.text.startsWith(`${slug}/`)) result.push(property.initializer.text);
      }
      ts.forEachChild(node, collect);
    };
    const visit = (node: ts.Node): void => {
      if (ts.isVariableDeclaration(node) && ['SETS', 'PLACE_SETS', 'REGIONS'].includes(node.name.getText(tree)) && node.initializer !== undefined) collect(node.initializer);
      if (ts.isCallExpression(node) && node.expression.getText(tree) === 'placeSet') for (const argument of node.arguments) collect(argument);
      ts.forEachChild(node, visit);
    };
    visit(tree);
  }
  return sorted(result);
}

async function capture(slug: string, side: string): Promise<Capture> {
  initializeTier('phone');
  const inputs: Record<string, string> = {}, gaps: string[] = [], infrastructureWarnings: string[] = [];
  const lists: Lists = { models: null, sets: null, world: null, arenas: null };
  if (side === 'legacy') {
    const module = async (file: string): Promise<Fields> => {
      inputs[file] = hash(readFileSync(file));
      const value: unknown = await import(pathToFileURL(resolve(file)).href); return object(value);
    };
    const { installLegacyKitSpecies } = await import('../src/game/systems/species/install');
    await installLegacyKitSpecies();
    if (slug === 'nalati-grasslands') (await import('../src/shards/nalati-grasslands-legacy/species/rows')).installNalatiSpeciesForTests();
    if (slug === 'driftwood-isle') (await import('../src/shards/driftwood-isle-legacy/species/install')).installDriftwoodSpecies();
    lists.models = ids((await module(`src/shards/${slug}-legacy/roster.ts`)).ROSTER);
    const manifest = object((await module(`src/shards/${slug}-legacy/manifest.ts`)).default);
    lists.world = ids(manifest.pois ?? []);
    lists.sets = legacySets(slug, inputs);
    lists.arenas = ['practice'];
    if (slug === 'nine-dragon-stack') lists.arenas.push((await import('../src/shards/nine-dragon-stack-legacy/playground/registration')).GRAPPLE_PLAYGROUND.id);
    if (slug === 'nalati-grasslands') lists.arenas.push((await import('../src/shards/nalati-grasslands-legacy/playground/registration')).horsePlayground(null).id);
    gaps.push('models: roster captured; world-placement registrations require a separate native world-list adapter');
    gaps.push('sets: literal id/place declaration union; conditional membership and computed identifiers are not qualified');
    gaps.push('world: manifest POIs captured; late runtime map registrations are not qualified');
  } else {
    const folder = inheritedProduct ?? resolve(root, 'out', slug), bytes = readFileSync(resolve(folder, 'shard.json'));
    if (inheritedProduct !== undefined && (inheritedIndex === undefined || hash(bytes) !== inheritedIndex)) throw new Error('Recorded product index changed');
    inputs[`out/${slug}/shard.json`] = hash(bytes);
    const raw: unknown = JSON.parse(bytes.toString('utf8')), index = parseOutputIndex(raw);
    const sections = new Map<string, unknown>();
    for (const row of index.sections) {
      const data = readFileSync(resolve(folder, row.path));
      if (data.byteLength !== row.bytes || hash(data) !== row.hash) throw new Error(`Invalid section ${row.name}`);
      const value: unknown = JSON.parse(data.toString('utf8')); sections.set(row.name, value);
    }
    const source = assembleOutputShardfile(raw, sections);
    const payloadUrl = (path: string): string => new URL(`/shardfiles/${slug}/${path}`, 'http://localhost').href;
    const readPayload = (hashId: string): Promise<Uint8Array> => {
      const row = index.files.find(file => file.hash === hashId); if (row === undefined) throw new Error(`Missing file ${hashId}`);
      const data = readFileSync(resolve(folder, row.path)); if (hash(data) !== hashId || data.byteLength !== row.compressed) throw new Error(`Invalid file ${row.path}`);
      inputs[`product:${slug}:${row.path}`] = hashId;
      return Promise.resolve(data);
    };
    const product = createShardProduct({ slug, revision: 0, shardfile: source, sections, builtJson: true,
      files: new Map(index.files.flatMap(row => row.name === undefined ? [] : [[row.name, { hash: row.hash, url: payloadUrl(row.path),
        ...(row.jsonSchema === undefined ? {} : { jsonSchema: row.jsonSchema }) }]])),
      read: readPayload });
    const features = rows(object(sections.get('client/plan')).features).map(object);
    const scope = new Scope('ld4-product-species'), species = new SpeciesService(() => scope);
    const environment = installBakeEnvironment(root);
    const originalError = console.error, diagnostics: string[] = [];
    console.error = (...args: unknown[]): void => {
      const only = args.length === 1 && typeof args[0] === 'string' ? args[0].trim() : null;
      if (only !== null && /^\(node:\d+\) ExperimentalWarning: Transform Types is an experimental feature and might change at any time(?:\n\(Use [^\n]+ to show where the warning was created\))?$/u.test(only)) infrastructureWarnings.push(only);
      else diagnostics.push(args.map(value => typeof value === 'string' ? value : value instanceof Error ? value.message : '[non-string diagnostic]').join(' '));
      originalError(...args);
    };
    try {
      // Same pure product catalogue and scoped service used by App/EngineRows;
      // no live-world wrapper, legacy seed, preload or specimen build.
      for (const feature of features.filter(row => row.kind === 'species.program')) {
        const catalogueSource = v.parse(ClientSpeciesProgramSchema, feature).catalogue;
        if (catalogueSource === undefined) continue;
        const actors = v.parse(v.object({ species: v.pick(SpeciesPresentationSchema, ['lookBook']) }), await product.json<unknown>(catalogueSource.actors));
        const catalogue = productSpeciesCatalogue(product, actors.species, await product.json<unknown>(catalogueSource.looks));
        for (const row of catalogue.rows) species.registerRow(row, scope);
        for (const row of catalogue.looks) species.registerLook(row, scope);
      }
      setSpeciesResolver(kind => species.get(kind));
      lists.models = await withPublicBytes(inputs, async () => (await explorerRoster(product)).map(row => row.id), url => {
        const file = index.files.find(row => payloadUrl(row.path) === url);
        return file === undefined ? undefined : readPayload(file.hash);
      });
      if (diagnostics.length > 0) throw new Error(`Catalogue source diagnostics: ${diagnostics.slice(0, 8).join('; ')}`);
    } catch (error) { lists.models = null; gaps.push(`models: ${error instanceof Error ? error.message : String(error)}`); }
    finally { console.error = originalError; try { scope.dispose(); } finally { environment.dispose(); } }
    lists.sets = features.filter(row => row.kind === 'world.sets').flatMap(row => ids(row.rows));
    lists.world = ids(object(object(sections.get('ui/level')).manifest).pois ?? []);
    lists.arenas = ['practice', ...features.filter(row => row.kind === 'practice.course').flatMap(row => {
      const course = row.course; if (typeof course !== 'string') throw new Error('Missing course'); return [course];
    })];
    gaps.push('models/sets: late native and world.assembly registrations are not qualified by the declared catalogue');
    gaps.push('world: ui/level manifest POIs captured; late runtime map registrations are not qualified');
    gaps.push('product: hash-verified existing output; no claim that it matches current source or visual/physics parity');
  }
  for (const key of Object.keys(lists) as (keyof Lists)[]) { const list = lists[key]; if (list !== null) lists[key] = sorted(list); }
  return { lists, inputs, gaps, infrastructureWarnings };
}

const [side, slug, destination] = process.argv.slice(2);
if (side === '--legacy' || side === '--shardfile') {
  if (slug === undefined || !slugs.includes(slug)) throw new Error('Unknown shard');
  console.log(JSON.stringify(await capture(slug, side.slice(2))));
} else {
  if (side === undefined) throw new Error('Usage: node --experimental-transform-types --import ./scripts/bake-loader.mjs scripts/legacy-explorer-lists.ts <report.json>');
  const recorded = side === '--recorded-cache';
  const output = recorded ? slug : side;
  if (output === undefined || destination !== undefined || !recorded && (slug !== undefined || side.startsWith('-'))) throw new Error('Unexpected argument');
  const expected = new Map<string, string>();
  if (recorded) {
    const previous: unknown = JSON.parse(execFileSync('git', ['show', `${revision}:docs/plans/shard-platform/legacy-explorer-lists.json`], { encoding: 'utf8' }));
    for (const row of rows(object(previous).shards).map(object)) {
      const name = row.shard, inputs = object(object(row.shardfile).inputs);
      if (typeof name !== 'string') throw new Error('Missing recorded shard');
      const index = inputs[`out/${name}/shard.json`];
      if (typeof index !== 'string' || !/^[a-f0-9]{64}$/u.test(index)) throw new Error('Missing recorded index hash');
      expected.set(name, index);
    }
  }
  const script = import.meta.filename;
  const report = slugs.map(name => {
    const read = (mode: string, folder?: string): Capture => {
      const bytes = execFileSync(process.execPath, ['--experimental-transform-types', '--import', './scripts/bake-loader.mjs', script, mode, name], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, env: { ...process.env, WS_LD4_REVISION: revision,
        ...(folder === undefined ? {} : { WS_LD4_PRODUCT_DIRECTORY: folder, WS_LD4_INDEX_HASH: expected.get(name) }) } });
      const value: unknown = JSON.parse(bytes); const row = object(value);
      // Child data is still parsed and checked before comparison.
      const lists = object(row.lists);
      for (const key of ['models', 'sets', 'world', 'arenas']) if (lists[key] !== null && rows(lists[key]).some(id => typeof id !== 'string')) throw new Error('Invalid child list');
      return value as Capture;
    };
    const legacy = read('--legacy');
    const cached = (): Capture => {
      const base = resolve(shardfileCacheRoot(), name), index = expected.get(name);
      if (index === undefined) throw new Error(`No recorded product for ${name}`);
      for (const entry of readdirSync(base, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        if (!entry.isDirectory() || !/^[a-f0-9]{64}$/u.test(entry.name)) continue;
        const folder = resolve(base, entry.name), release = borrowShardfileEntry(folder);
        try {
          if (existsSync(`${folder}.lock`) || readBuildKey(folder) !== entry.name) continue;
          if (hash(readFileSync(resolve(folder, 'shard.json'))) === index) return read('--shardfile', folder);
        } finally { release(); }
      }
      throw new Error(`Exact recorded cache product unavailable: ${name}`);
    };
    const shardfile = recorded ? cached() : read('--shardfile');
    return { shard: name, legacy, shardfile, differences: Object.fromEntries(Object.keys(legacy.lists).map(key => {
      const list = key as keyof Lists, a = legacy.lists[list], b = shardfile.lists[list];
      return [key, a === null || b === null ? { qualified: false } : { qualified: list === 'arenas',
        missing: a.filter(id => !b.includes(id)), added: b.filter(id => !a.includes(id)) }];
    })) };
  });
  writeFileSync(resolve(output), `${JSON.stringify({ version: 1, source: revision, collectorHash: hash(readFileSync(import.meta.filename)), tier: 'phone',
    productSelection: recorded ? 'exact recorded index hashes from the existing cache' : 'active out products',
    coverage: { models: 'declared roster/catalogue only', sets: 'literal legacy declarations / world.sets rows only', world: 'manifest POIs only', arenas: 'common Developer practice and declared courses' }, shards: report }, null, 2)}\n`);
  console.log(`LD4: compared ${report.length} shards; coverage gaps remain explicit in the report`);
}
