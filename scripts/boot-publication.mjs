// Boot transport activation facts belong to the successful artifact publisher.
// Plain source formatters read those committed facts, never native tools,
// discovery modules, pack blobs or previously emitted TypeScript tables.
import { readFileSync, writeFileSync, renameSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import * as v from 'valibot';
import { contentNamed } from './app-build/assetHashes';

export const BOOT_PUBLICATION = 'scripts/boot-publication.generated.json';
const url = v.pipe(v.string(), v.maxLength(4096), v.check(value => value.startsWith('/assets/') && !/[\\?#]/u.test(value) && !/\p{Cc}/u.test(value) && value.split('/').slice(1).every(part => part !== '' && part !== '.' && part !== '..'), 'Invalid published asset URL'));
const bytes = v.pipe(v.number(), v.safeInteger(), v.minValue(0));
const sha8 = v.pipe(v.string(), v.regex(/^[a-f0-9]{8}$/u));
const row = v.strictTuple([url, bytes, bytes, v.pipe(v.string(), v.minLength(1), v.maxLength(128))]);
const part = v.strictObject({ url, bytes, files: v.pipe(v.array(row), v.minLength(1), v.maxLength(8192)) });
const definition = v.strictObject({ parts: v.pipe(v.array(part), v.minLength(1), v.maxLength(8192)) });
const schema = v.strictObject({ schema: v.literal('boot-publication/1'),
  bytes: v.record(url, bytes), versions: v.record(url, sha8),
  packs: v.record(v.pipe(v.string(), v.regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/u)), v.record(v.picklist(['phone', 'desktop']), definition)),
});

/** Full publication admission checks offsets and byte charges before formatting.
 * @param {unknown} input */
export function parseBootPublication(input) {
  const data = v.parse(schema, input);
  if (Object.keys(data.bytes).length > 50_000) throw new Error('Published asset inventory exceeds cap');
  for (const name of Object.keys(data.bytes)) if (!contentNamed(name) && !Object.hasOwn(data.versions, name)) throw new Error(`Published asset lacks content version: ${name}`);
  for (const name of Object.keys(data.versions)) if (!Object.hasOwn(data.bytes, name)) throw new Error(`Published version lacks byte charge: ${name}`);
  for (const [slug, tiers] of Object.entries(data.packs)) for (const [tier, value] of Object.entries(tiers)) {
    const seen = new Set();
    for (const item of value.parts) {
      if (!new RegExp(`^/assets/packs/${slug}\\.${tier}-[a-f0-9]{8}\\.bin$`, 'u').test(item.url)) throw new Error('Published pack identity differs');
      let offset = 0;
      for (const [name, start, length] of item.files) {
        if (seen.has(name) || start !== offset || data.bytes[name] !== length) throw new Error(`Published pack file charge differs: ${name}`);
        seen.add(name); offset += length;
      }
      if (!Number.isSafeInteger(offset) || offset !== item.bytes) throw new Error('Published pack byte total differs');
    }
  }
  return data;
}

/** @param {string} root */
export function readBootPublication(root) {
  const source = readFileSync(resolve(root, BOOT_PUBLICATION));
  if (source.length > 5_000_000) throw new Error('Boot publication exceeds cap');
  return parseBootPublication(JSON.parse(source.toString('utf8')));
}

/** Publish only the successful pack writer's complete byte/hash/part inventory.
 * @param {string} root @param {unknown} input */
export function publishBootPublication(root, input) {
  const data = parseBootPublication(input), text = `${JSON.stringify(data, null, 2)}\n`;
  if (Buffer.byteLength(text) > 5_000_000) throw new Error('Boot publication exceeds cap');
  const path = resolve(root, BOOT_PUBLICATION), temporary = `${path}.${randomUUID()}.tmp`;
  try {
    try { if (readFileSync(path, 'utf8') === text) return; } catch (error) {
      if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error;
    }
    writeFileSync(temporary, text, { flag: 'wx' }); renameSync(temporary, path);
  } finally { rmSync(temporary, { force: true }); }
}

/** @param {ReturnType<typeof parseBootPublication>['packs']} packs */
function prettyPacks(packs) {
  const partText = (/** @type {v.InferOutput<typeof part>} */ item) => [
    '      {', `        url: ${JSON.stringify(item.url)},`, `        bytes: ${item.bytes},`, '        files: [',
    ...item.files.map(file => `          ${JSON.stringify(file)},`), '        ],', '      },',
  ].join('\n');
  const tierText = (/** @type {string} */ name, /** @type {v.InferOutput<typeof definition>} */ value) => [`    ${JSON.stringify(name)}: pack([`, ...value.parts.map(partText), '    ]),'].join('\n');
  return ['{', ...Object.entries(packs).map(([slug, tiers]) => [`  ${JSON.stringify(slug)}: {`, ...Object.entries(tiers).map(([tier, value]) => tierText(tier, value)), '  },'].join('\n')), '}'].join('\n');
}

const HEADER = '// Generated by gen:source (scripts/boot-publication.mjs) from committed boot publication facts; do not edit.\n';

/** @param {ReturnType<typeof parseBootPublication>} data */
export function publishedBootTableSources(data) {
  return {
    'src/game/boot/bytes.generated.ts': publicBytesTableSource(data.bytes),
    'src/game/boot/versions.generated.ts': assetVersionsTableSource(data.versions),
    'src/game/boot/packs.generated.ts': `${HEADER}// slug → tier → the boot pack, in content-addressed parts: each part's URL, size and [path, offset in the part, size,
// content-type] per packed file (src/engine/boot/pack.ts). \`files\` / \`bytes\` are the whole pack's.
import type { PackDef, PackPart } from '@wildshard/engine/boot/tables';
const pack = (parts: readonly PackPart[]): PackDef => ({ parts, bytes: parts.reduce((s, p) => s + p.bytes, 0), files: parts.flatMap((p) => p.files) });
export const PACKS: Readonly<Record<string, Readonly<Record<string, PackDef>>>> = ${prettyPacks(data.packs)};
`,
  };
}

/** @param {Readonly<Record<string,number>>} rows */
export function publicBytesTableSource(rows) {
  return `${HEADER}export const PUBLIC_BYTES = {\n${Object.keys(rows).sort().map(name => `  ${JSON.stringify(name)}: ${rows[name]},`).join('\n')}\n} as const;\n`;
}
/** @param {Readonly<Record<string,string>>} rows */
export function assetVersionsTableSource(rows) {
  return `${HEADER}export const ASSET_VERSIONS: Readonly<Record<string, string>> = {\n${Object.entries(rows).map(([name, hash]) => `  ${JSON.stringify(name)}: '${hash}',`).join('\n')}\n};\n`;
}

/** @param {string} root */
export function bootPublicationTableSources(root) { return publishedBootTableSources(readBootPublication(root)); }
