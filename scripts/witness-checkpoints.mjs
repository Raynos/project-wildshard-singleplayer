// Native checkpoint hash metadata; the explicit native recorder owns caching and publication.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import * as v from 'valibot';

const digest = v.pipe(v.string(), v.regex(/^[0-9a-f]{64}$/u));
const fileName = v.pipe(v.string(), v.regex(/^[a-zA-Z0-9_-]+(?:\.snap|\.json)?\.(?:gz|json)$/u));
/** Every bounded regular checkpoint file and its SHA256; never follow directories or links.
 * @param {string} dir */
export function checkpointHashes(dir) {
  const files = readdirSync(dir, { withFileTypes: true });
  if (files.length === 0 || files.length > 64) throw new Error('Invalid checkpoint file count');
  return Object.fromEntries(files.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0).map(entry => {
    v.parse(fileName, entry.name);
    if (!entry.isFile()) throw new Error(`Invalid checkpoint file ${entry.name}`);
    const path = resolve(dir, entry.name);
    if (statSync(path).size > 64 * 1024 * 1024) throw new Error(`Unbounded checkpoint file ${entry.name}`);
    return [entry.name, createHash('sha256').update(readFileSync(path)).digest('hex')];
  }));
}

const Metadata = v.strictObject({ version: v.literal(1), notice: v.literal('DO NOT EDIT: generated by the retained TypeScript witness; run.mjs checkpoints regenerates and compares.'), payloads: v.record(fileName, digest) });

/** Read the validated committed hash table without requiring old generated payloads in the source directory.
 * Native readers validate actual cache files through the shared runner before admitting a continuation.
 * @param {string | URL} file @returns {Record<string, string> | undefined} */
export function witnessPayloadHashes(file) {
  const parsed = v.parse(v.record(v.string(), v.unknown()), JSON.parse(readFileSync(file, 'utf8')));
  return parsed.cache === undefined ? undefined : v.parse(Metadata, parsed.cache).payloads;
}

/** Read the native outcome while validating and removing only the cache transport metadata.
 * @param {string | URL} file @returns {Record<string, unknown>} */
export function readWitnessManifest(file) {
  const parsed = v.parse(v.record(v.string(), v.unknown()), JSON.parse(readFileSync(file, 'utf8')));
  if (parsed.cache !== undefined) v.parse(Metadata, parsed.cache);
  const { cache: _cache, ...outcome } = parsed;
  return outcome;
}

/** Add a small, reproducible hash table to a native manifest without committing its generated payloads.
 * @param {string} directory @returns {string} */
export function cachedWitnessManifest(directory) {
  const file = resolve(directory, 'manifest.json'), outcome = readWitnessManifest(file);
  const { 'manifest.json': _manifest, ...payloads } = checkpointHashes(directory);
  if (Object.keys(payloads).length === 0) throw new Error('Witness generated no checkpoint payloads');
  const cache = v.parse(Metadata, { version: 1, notice: 'DO NOT EDIT: generated by the retained TypeScript witness; run.mjs checkpoints regenerates and compares.', payloads });
  return `${JSON.stringify({ ...outcome, cache }, null, 2)}\n`;
}

/** Fields Linux records exactly as Darwin does, measured on CI run 42367941424: Pine's ticks and canonical hashes, and
 * Driftwood's ticks, effects and each checkpoint's name, tick and profile. Gzip payload hashes differ by host, and
 * Driftwood's `sha`, `digest`, `endDigest` and `tape` carry float state that differs on Linux.
 * @param {Record<string, unknown>} outcome */
function portableOutcome({ ticks, hashes, effects, checkpoints }) {
  const rows = v.parse(v.optional(v.array(v.looseObject({ name: v.string(), tick: v.number(), profile: v.unknown() }))), checkpoints);
  return { ticks, hashes, effects, checkpoints: rows?.map(({ name, tick, profile }) => ({ name, tick, profile })) };
}

/** Two manifests that played nothing would match, and the match would prove nothing (E7's empty room).
 * @param {Record<string, unknown>} outcome */
function assertPlayed({ ticks }) {
  const counts = typeof ticks === 'number' ? [ticks] : Object.values(v.parse(v.optional(v.record(v.string(), v.number()), {}), ticks));
  if (!counts.some(count => count > 0)) throw new Error('Witness played no ticks; its match would prove nothing');
}

/** Validate a regenerated witness against the committed one. Darwin compares it whole: native bit identity is normative
 * there. Other hosts compare the portable outcome, so a behaviour drift goes red on Linux too.
 * @param {string} expected @param {string} actual @param {string} [platform] */
export function compareWitnessManifests(expected, actual, platform = process.platform) {
  /** @param {string} text */
  const parse = (text) => {
    const manifest = v.parse(v.record(v.string(), v.unknown()), JSON.parse(text));
    v.parse(Metadata, manifest.cache);
    const { inputs: _inputs, ...outcome } = manifest;
    return outcome;
  };
  const before = parse(expected), after = parse(actual);
  assertPlayed(before); assertPlayed(after);
  const same = platform === 'darwin' ? JSON.stringify(before) === JSON.stringify(after)
    : JSON.stringify(portableOutcome(before)) === JSON.stringify(portableOutcome(after));
  if (!same) throw new Error('Regenerated witness hashes or outcomes changed; record this behaviour change deliberately');
}
