#!/usr/bin/env node
// gen-port-shares.mjs — SHARD SELECT's "N% PORTED" badge (SF65 G238) from the plan ruler (E486, Jake 2026-10-17: "every
// time you run the ruler, you save it into a JSON file that gets committed, and then the lint check can be really cheap
// at pre-commit to see if the number matches").
//
//   node scripts/gen-port-shares.mjs            rewrite src/game/shard/portShares.json from the committed ruler.json
//   node scripts/gen-port-shares.mjs --check    exit 1 when the two working-tree files disagree
//
// The ruler (scripts/admin-data/ruler.mjs) writes progress/shard-platform/ruler/ruler.json and then this table, and
// commits both. Each legacy shard's ported share is 1 − pct / 100 (pct = custom lines as a percent of its frozen legacy
// lines), so Sky Reach at 7.7 % custom reads 92 % PORTED. The table is committed because the Vercel build has no
// progress/ (.vercelignore); scripts/precommit-inputs.mjs refuses a commit whose staged table and staged ruler disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const RULER_JSON = 'progress/shard-platform/ruler/ruler.json';
export const PORT_SHARES_JSON = 'src/game/shard/portShares.json';
const FIX = 'run `node scripts/gen-port-shares.mjs` and commit src/game/shard/portShares.json with ruler.json';

/** @param {unknown} value @returns {value is Record<string, unknown>} */
const isObject = (value) => typeof value === 'object' && value !== null && !Array.isArray(value);

/**
 * The table's exact text for one ruler.json body.
 * @param {string} rulerText
 * @returns {string}
 */
export function portSharesText(rulerText) {
  const ruler = /** @type {unknown} */ (JSON.parse(rulerText));
  if (!isObject(ruler) || typeof ruler.revision !== 'string' || typeof ruler.measuredAt !== 'string' || !Array.isArray(ruler.shards)) {
    throw new Error(`port-shares: ${RULER_JSON} has no revision, measuredAt or shards`);
  }
  /** @type {Record<string, number>} */
  const shares = {};
  for (const row of /** @type {unknown[]} */ (ruler.shards)) {
    // An unmeasured shard has no numeric badge, rather than a stale or zero credit.
    if(isObject(row)&&typeof row.slug==='string'&&row.pct===null&&typeof row.measurementError==='string'&&row.measurementError!=='')continue;
    if (!isObject(row) || typeof row.slug !== 'string' || typeof row.pct !== 'number' || !Number.isFinite(row.pct)) {
      throw new Error(`port-shares: a ${RULER_JSON} shard row has no slug or numeric pct`);
    }
    shares[row.slug] = Math.round(Math.min(1, Math.max(0, 1 - row.pct / 100)) * 10_000) / 10_000;
  }
  const table = { note: `Generated by scripts/gen-port-shares.mjs from ${RULER_JSON}; do not edit.`, revision: ruler.revision, measuredAt: ruler.measuredAt, shares };
  return `${JSON.stringify(table, null, 2)}\n`;
}

/**
 * Null when the table matches what the ruler implies, else the reason and the fix.
 * @param {string | undefined} rulerText
 * @param {string | undefined} sharesText
 * @returns {string | null}
 */
export function portSharesMismatch(rulerText, sharesText) {
  if (rulerText === undefined) return `port-shares: ${RULER_JSON} is missing`;
  let want;
  try { want = portSharesText(rulerText); } catch (error) { return error instanceof Error ? error.message : String(error); }
  if (sharesText === want) return null;
  return `port-shares: ${PORT_SHARES_JSON} does not match ${RULER_JSON} (the SHARD SELECT "N% PORTED" badges would be stale); ${FIX}.`;
}

/** @param {string} root */
export function writePortShares(root = resolve(import.meta.dirname, '..')) {
  const text = portSharesText(readFileSync(resolve(root, RULER_JSON), 'utf8'));
  writeFileSync(resolve(root, PORT_SHARES_JSON), text);
  return text;
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  const root = resolve(import.meta.dirname, '..');
  if (process.argv.includes('--check')) {
    const read = (/** @type {string} */ path) => { try { return readFileSync(resolve(root, path), 'utf8'); } catch { return undefined; } };
    const reason = portSharesMismatch(read(RULER_JSON), read(PORT_SHARES_JSON));
    if (reason) { console.error(reason); process.exitCode = 1; }
  } else {
    writePortShares(root);
    console.info(`port-shares: ${PORT_SHARES_JSON} from ${RULER_JSON}`);
  }
}
