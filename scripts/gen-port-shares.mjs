import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { shardLines } from './shard-platform.mjs';

/** SF65 (G238): SHARD SELECT's "N% PORTED" badge, measured at build time by the SF6 metric (scripts/shard-platform.mjs, the
 *  G291 retained-runtime reduction, or legacy-share without a frozen copy), so the menu never runs the script. Written to a gitignored table on every `pnpm gen`. */
export function genPortShares(root = process.cwd()) {
  const shares = Object.fromEntries(Object.entries(shardLines(root)).map(([slug, row]) => [slug, Math.round((row.conversion.runtimeShare === null ? row.legacyShare : Math.max(0, 1 - row.conversion.runtimeShare)) * 10_000) / 10_000]));
  const out = resolve(root, 'src/game/shard/portShares.generated.ts');
  const source = `// Generated by scripts/gen-port-shares.mjs (pnpm gen) from scripts/shard-platform.mjs: each shard's G291 retained-runtime reduction (legacy-share without a frozen copy), 0..1.\nexport const PORT_SHARES: Readonly<Record<string, number>> = ${JSON.stringify(shares, null, 2)};\n`;
  let previous = '';
  try { previous = readFileSync(out, 'utf8'); } catch { /* first generation */ }
  if (previous !== source) { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, source); }
}
