import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { starterBagPack } from '../src/commons/packs/bag/pack.ts';

/** Build-only pack expansion; boot imports this literal table and never commons code. */
export function starterBagTableSource() {
  const entry = starterBagPack({ credit: 'Wildshard', licence: 'First-party' }).entries.at(0);
  if (entry === undefined) throw new Error('Starter bag pack has no rows');
  const json = new TextDecoder().decode(entry.bytes);
  return `// Generated by scripts/gen-starter-bag.mjs from the commons bag pack; do not edit.\nexport const STARTER_BAG_ITEMS = ${json} as const;\n`;
}
/** Generate on every normal build, clean export and test setup through pnpm gen. */
export function genStarterBag(root = process.cwd()) {
  const output = resolve(root, 'src/game/bag/starter.generated.ts'), source = starterBagTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
