import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import items from '../src/game/bag/starterItems.json' with { type: 'json' };

/** Build-only expansion of the authored starter rows; boot imports this literal table. */
export function starterBagTableSource() {
  const json = JSON.stringify(items);
  return `// Generated by scripts/gen-starter-bag.mjs from src/game/bag/starterItems.json; do not edit.\nexport const STARTER_BAG_ITEMS = ${json} as const;\n`;
}
/** Generate on every normal build, clean export and test setup through pnpm gen. */
export function genStarterBag(root = process.cwd()) {
  const output = resolve(root, 'src/game/bag/starter.generated.ts'), source = starterBagTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
