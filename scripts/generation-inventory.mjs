// G292 report: committed content only, never another lane's staged or working-tree outputs.
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import * as v from 'valibot';

/** G292 retention decision; an unknown duration is never called expensive.
 * @param {{bytes:number,seconds:number|null,darwinOnly:boolean|null,blender:boolean,frozen:boolean}} row */
export function outputPolicy(row) {
  if (row.frozen) return 'retain frozen baseline';
  if (row.blender) return 'retain Blender (G293)';
  if (row.darwinOnly === true) return 'retain Darwin normative';
  if (row.bytes < 200_000 && row.seconds !== null && row.seconds > 60) return 'retain small + expensive';
  return 'build/cache candidate; retain pending proof';
}

/** Every requested generated-content family, including extensionless compiled blobs.
 * @param {string} file @param {string} [header] */
export function generatedContent(file, header = '') {
  return /(?:^|\/)(?:baked|gpu|checkpoints)\//u.test(file) || /\/map\/(?:top|height)\.(?:webp|png|jpg)$/u.test(file)
    || /\.(?:generated|baked)\./u.test(file) || /\.(?:snap\.gz|pack|ws-pack|ktx2|wasm)$/u.test(file) || /\.(?:phone|desktop)\./u.test(file)
    || /(?:^|\/)(?:physics|spots)\.baked\.json$/u.test(file)
    || file.startsWith('public/shardfiles/') || /^src\/shards\/[^/]+\/assets\/[a-f0-9]{64}$/u.test(file)
    || /^scripts\/.*\.(?:cache|list)\.json$/u.test(file)
    || /\/packs\//u.test(file) || /\.(?:phone\.)?rigged\.glb$/u.test(file)
    || /^\s*(?:\/\/|\/\*)[^\n]*(?:@generated|auto-generated|autogenerated|Generated by\b|DO[- ]NOT[- ]EDIT)/imu.test(header);
}

/** Itemize the immutable Git tree. Missing producer/timing/platform evidence stays explicit.
 * @param {string} root @param {string} [revision] */
export function inventoryOutputs(root, revision = 'HEAD') {
  const git = (/** @type {string[]} */ args) => execFileSync('git', args, {cwd:root,encoding:'utf8',maxBuffer:64*1024*1024});
  const pin = git(['rev-parse',revision]).trim();
  const files = git(['ls-tree','-r','-l',pin]).trim().split('\n').map(line => {
    const tab=line.indexOf('\t');
    if(tab===-1) throw new Error('Malformed committed file inventory');
    const metadata=line.slice(0,tab), path=line.slice(tab+1);
    const size = Number(metadata.split(/\s+/u).at(-1));
    if (!Number.isSafeInteger(size) || size < 0) throw new Error(`Unbounded committed output ${path}`);
    return {path,bytes:size};
  });
  /** @type {Map<string,string>} */
  const texts = new Map();
  const readable = files.filter(row => /\.(?:mjs|ts|tsx)$/u.test(row.path) && row.bytes < 4_000_000).map(row=>row.path);
  const batch = execFileSync('git',['cat-file','--batch'],{cwd:root,input:readable.map(path=>`${pin}:${path}\n`).join(''),maxBuffer:128*1024*1024});
  let cursor=0;
  for (const path of readable) {
    const end=batch.indexOf(10,cursor), header=batch.subarray(cursor,end).toString(), count=Number(header.split(' ').at(-1));
    if (end === -1 || !Number.isSafeInteger(count) || count < 0) throw new Error(`Malformed source blob ${path}`);
    texts.set(path,batch.subarray(end+1,end+1+count).toString());cursor=end+count+2;
  }
  const text = (/** @type {string} */ path) => { const previous=texts.get(path);if(previous!==undefined)return previous;const source=git(['show',`${pin}:${path}`]);texts.set(path,source);return source; };
  const bakers = files.filter(({path}) => /(?:^scripts\/bake-|^src\/shards\/[^/]+\/generators\/bake-).*\.(?:mjs|ts)$/u.test(path)).map(({path}) => path);
  const {targets} = v.parse(v.object({targets:v.record(v.string(),v.object({outputs:v.optional(v.array(v.string()))}))}),JSON.parse(text('scripts/blender/targets.json')));
  /** @type {Map<string,string>} */
  const blender = new Map();
  for (const [id,target] of Object.entries(targets)) {
    for (const file of target.outputs ?? []) blender.set(file,`scripts/blender/build.sh ${id}`);
  }
  const legacy = v.parse(v.object({shards:v.record(v.string(),v.object({files:v.record(v.string(),v.string())}))}),JSON.parse(text('lint/legacy-shards.json'))).shards;
  const frozen = new Set(Object.entries(legacy).flatMap(([slug,row])=>Object.keys(row.files).map(file=>`src/shards/${slug}/${file}`)));
  const rows = [];
  for (const row of files) {
    const header = /^src\/shards\/.*\.(?:ts|tsx)$/u.test(row.path) && row.bytes < 4_000_000 ? text(row.path).slice(0,512) : '';
    const declaredData = /\.(?:json|bin|glb|ktx2|png|webp)$/u.test(row.path)
      && bakers.some(baker => text(baker).includes(row.path));
    if (!generatedContent(row.path,header) && !blender.has(row.path) && !declaredData && !['lint/ratchet.json','lint/layer-edges.json','scripts/README.md'].includes(row.path)) continue;
    let generator = blender.get(row.path) ?? null;
    if (generator === null && (row.path === 'lint/ratchet.json' || row.path === 'lint/layer-edges.json' || row.path === 'scripts/README.md')) generator='scripts/generated-files.mjs';
    const local = /^src\/shards\/([^/]+)\//u.exec(row.path)?.[1];
    const asset = /^public\/assets\/(?:baked\/)?([^/]+)\//u.exec(row.path)?.[1];
    const owner = local ?? (asset === 'nalati' ? 'nalati-grasslands' : asset === 'nine-dragon' ? 'nine-dragon-stack' : asset);
    if (generator === null && (/\/map\//u.test(row.path) || row.path.endsWith('/look/map.baked.json'))) generator='scripts/bake-maps.mjs';
    if (generator === null && /^test\/proof\/([^/]+)\/checkpoints\//u.test(row.path)) generator=`test/proof/${row.path.split('/')[2]}/run.mjs checkpoints`;
    if (generator === null && row.path.endsWith('.ws-pack')) generator='scripts/bake-packs.mjs';
    if (generator === null && row.path.startsWith('public/assets/gpu/')) generator='scripts/bake-ktx2.mjs (overlay producers also required)';
    if (generator === null) {
      const stem = (row.path.split('/').at(-1) ?? '').replace(/\.(?:phone|desktop)?\.?[a-z0-9]+$/u,'').replace(/\.baked$/u,'').replaceAll(/[A-Z]/gu,c=>`-${c.toLowerCase()}`);
      const candidates = bakers.filter(baker => baker.startsWith(`src/shards/${owner}/generators/`) && (text(baker).includes(row.path) ? true : baker.endsWith(`-${stem}.mjs`)));
      if (candidates.length === 1) generator=candidates[0] ?? null;
    }
    if (generator === null && /^public\/assets\/baked\/[^/]+\/terrain\.bin$/u.test(row.path)) generator='scripts/bake-chunk.mjs';
    if (generator === null && row.path.startsWith('public/assets/baked/template-props/')) generator='src/shards/_template/generators/kit.ts + scripts/build-shardfiles.mjs';
    const darwinOnly = owner === 'nine-dragon-stack' && /\/(?:layout|specimens(?:-explorer)?)\.(?:bin|json)$/u.test(row.path) ? true : null;
    const item = {...row,generator,seconds:null,darwinOnly,blender:blender.has(row.path) && row.path.endsWith('.glb'),frozen:frozen.has(row.path)};
    rows.push({...item,policy:outputPolicy(item)});
  }
  return {pin,rows};
}

/** Compact table with one row per committed file; bytes and unknown evidence are never guessed.
 * @param {ReturnType<typeof inventoryOutputs>} inventory */
export function inventoryMarkdown(inventory) {
  const {pin,rows}=inventory, total=rows.reduce((sum,row)=>sum+row.bytes,0);
  return [`# G292 committed generated outputs\n\nSource: committed ${pin}. Report-only: no output is deleted or uncommitted by this inventory.\n\n`,
    `${rows.length} files, ${total} bytes. Blender GLBs remain committed (G293); Darwin-normative outputs remain committed. Other outputs default to build-time + content-hash cache. A committed exception requires **both** <200,000 bytes and a measured cold regenerate time >60 s. Missing timing is not an exception.\n\n`,
    `Generation times are not consistently recorded per producer in the existing receipts. They remain unavailable here; the shared runner records elapsedMs on real cold executions. Darwin-only = yes only where the existing byte oracle explicitly restricts itself to macOS; unknown is not a portability claim.\n\n`,
    `Unresolved producer rows are migration blockers, not permission to delete their outputs. Frozen legacy outputs remain sealed. The table covers baked/GPU directories, maps, native captures, packs, checkpoint files, compiled shard blobs, marked generated TS, declared data outputs and Blender target outputs. Authored data and third-party input assets are not generated outputs.\n\n`,
    `| Committed output | Bytes | Producer | Cold seconds | Darwin-only exact | G292 disposition |\n|---|---:|---|---:|---|---|\n`,
    rows.map(row=>`| ${row.path} | ${row.bytes} | ${row.generator ?? 'UNRESOLVED'} | unavailable | ${row.darwinOnly === true ? 'yes' : 'unproven'} | ${row.policy} |`).join('\n'), `\n`].join('');
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root=resolve(import.meta.dirname,'..'), report=inventoryMarkdown(inventoryOutputs(root));
  const output=process.argv.find(arg=>arg.startsWith('--out='))?.slice(6);
  if (output === undefined) process.stdout.write(report); else writeFileSync(resolve(root,output),report);
}
