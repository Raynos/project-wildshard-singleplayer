import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import bow from '../src/game/weapons/starterBow.json' with { type: 'json' };

/** Expand the authored shared bow data (Nalati and Pine) into a literal table. */
export function starterWeaponsTableSource() {
  const json = JSON.stringify(bow);
  return `// Generated by scripts/gen-starter-weapons.mjs from src/game/weapons/starterBow.json; DO NOT EDIT.\nexport const STARTER_BOW = ${json} as const;\n`;
}
/** Generate before producers read weapon recipes and on ordinary Vite boot-table builds. */
export function genStarterWeapons(root = process.cwd()) {
  const output = resolve(root, 'src/game/weapons/starter.generated.ts'), source = starterWeaponsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
