import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { starterWeaponsPack } from '../src/commons/packs/weapons/pack.ts';

/** Expand the authored shared bow data without pulling build-time commons code into the browser. */
export function starterWeaponsTableSource() {
  const entry = starterWeaponsPack({ credit: 'Wildshard', licence: 'First-party' }).entries.at(0);
  if (entry === undefined) throw new Error('Starter weapons pack has no bow data');
  const json = new TextDecoder().decode(entry.bytes);
  return `// Generated by scripts/gen-starter-weapons.mjs from the commons weapons pack; DO NOT EDIT.\nexport const STARTER_BOW = ${json} as const;\n`;
}
/** Generate before producers read weapon recipes and on ordinary Vite boot-table builds. */
export function genStarterWeapons(root = process.cwd()) {
  const output = resolve(root, 'src/game/weapons/starter.generated.ts'), source = starterWeaponsTableSource();
  let previous = '';
  try { previous = readFileSync(output, 'utf8'); } catch { /* First generation. */ }
  if (previous !== source) { mkdirSync(dirname(output), { recursive: true }); writeFileSync(output, source); }
}
