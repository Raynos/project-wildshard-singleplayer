#!/usr/bin/env node
// DL21 (Jake on live 69fa647: "lol what's this", an unstyled card at 00:03.2): the loading card the document paints before
// any module or extracted stylesheet arrives is the same card Loading adopts, so it carries the same CSS from the first
// frame. This copies the card's own stylesheets (the shared tokens and glass of base.css, then loading.css) into
// index.html's first-paint <style>, between its markers; test/inline-shell-css.test.mjs refuses a copy that drifted.
//   node scripts/inline-shell-css.mjs           # rewrite the block
//   node scripts/inline-shell-css.mjs --check   # exit 1 when index.html's block is not today's sheets
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
export const SHELL_SHEETS = ['src/engine/ui/styles/base.css', 'src/engine/ui/loading.css'];
const OPEN = '/* <inline-shell-css> generated by scripts/inline-shell-css.mjs from base.css + loading.css: do not edit */';
const CLOSE = '/* </inline-shell-css> */';

/** index.html with its marked block holding `sheets` (read from the repo), the rest of the document unchanged. */
export function inlineShellCss(html, read = (path) => readFileSync(resolve(ROOT, path), 'utf8')) {
  const block = `${OPEN}\n${SHELL_SHEETS.map(path => read(path).trim()).join('\n')}\n${CLOSE}`;
  const from = html.indexOf(OPEN), to = html.indexOf(CLOSE);
  if (from === -1 || to === -1 || to < from || html.includes(OPEN, from + 1)) throw new Error('index.html needs exactly one inline-shell-css block');
  return html.slice(0, from) + block + html.slice(to + CLOSE.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = resolve(ROOT, 'index.html'), html = readFileSync(path, 'utf8'), next = inlineShellCss(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('index.html: the inline shell CSS differs from base.css + loading.css; run node scripts/inline-shell-css.mjs'); process.exit(1); }
  } else if (next !== html) writeFileSync(path, next);
}
