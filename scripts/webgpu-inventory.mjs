#!/usr/bin/env node
// E357 X6: the WebGPU port inventory — every place a renderer port has to touch, as a checklist.
// `node scripts/webgpu-inventory.mjs` rewrites docs/design/webgpu-port-inventory.md; `--check` fails when it is stale
// (test/webgpu-inventory.test.ts runs the check inside `pnpm test`).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const DOC = 'docs/design/webgpu-port-inventory.md';

function files(dir) {
  const out = [];
  for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...files(path));
    else if (/\.(ts|mts|js|mjs)$/u.test(entry.name) && !entry.name.endsWith('.d.ts')) out.push(path);
  }
  return out;
}

const count = (text, re) => (text.match(re) ?? []).length;

/** the inventory rows, from the source tree under `src/` */
export function inventory() {
  const shaderMaterials = [], post = [], patches = [], keys = [], chunks = [], renderer = [];
  for (const file of files('src').sort()) {
    const text = readFileSync(join(ROOT, file), 'utf8');
    const sm = count(text, /\bnew (?:THREE\.)?(?:Raw)?ShaderMaterial\b/gu);
    if (sm) shaderMaterials.push([file, sm]);
    if (/from 'postprocessing'/u.test(text)) post.push(file);
    // an id is a string literal, or an expression choosing between literals (each listed)
    for (const m of text.matchAll(/\bpatchShader\([^,]+, ([^,]+), PATCH_ORDER\.(\w+)/gu)) {
      for (const id of m[1].match(/'[^']+'/gu) ?? [m[1].trim()]) patches.push([id.replaceAll("'", ''), m[2], file]);
    }
    for (const m of text.matchAll(/\bsetProgramKey\([^,]+, '([^']+)'\)/gu)) keys.push([m[1], file]);
    const ch = count(text, /\bShaderChunk\.\w+\s*(?:\+?=)(?!=)/gu);
    if (ch) chunks.push([file, ch]);
    if (!file.startsWith('src/engine/render/') && /\bWebGLRenderer\b/u.test(text)) renderer.push(file);
  }
  return { shaderMaterials, post, patches, keys, chunks, renderer };
}

export function render(inv = inventory()) {
  const total = (rows) => rows.reduce((n, [, c]) => n + c, 0);
  const lines = [
    '# WebGPU port inventory',
    '',
    'Generated by `node scripts/webgpu-inventory.mjs` (E357 X6, decision 22); `pnpm test` fails when it is stale. Every row is a',
    'place a renderer port has to touch. The renderer type is `Renderer` (`src/engine/render/renderer.ts`); every',
    '`onBeforeCompile` edit is a `patchShader` id in `src/engine/render/shaderPatches.ts`. No TSL, no WebGPURenderer.',
    '',
    `## Shader patches (${inv.patches.length})`,
    '',
    '| Patch id | Order band | File |',
    '|---|---|---|',
    ...inv.patches.map(([id, order, file]) => `| \`${id}\` | ${order} | ${file} |`),
    '',
    `## Program keys without a patch (${inv.keys.length})`,
    '',
    '| Key | File |',
    '|---|---|',
    ...inv.keys.map(([key, file]) => `| \`${key}\` | ${file} |`),
    '',
    `## ShaderMaterial / RawShaderMaterial (${total(inv.shaderMaterials)} in ${inv.shaderMaterials.length} files)`,
    '',
    '| File | Uses |',
    '|---|---|',
    ...inv.shaderMaterials.map(([file, n]) => `| ${file} | ${n} |`),
    '',
    `## Global ShaderChunk edits (${total(inv.chunks)} in ${inv.chunks.length} files)`,
    '',
    '| File | Edits |',
    '|---|---|',
    ...inv.chunks.map(([file, n]) => `| ${file} | ${n} |`),
    '',
    `## postprocessing files (${inv.post.length})`,
    '',
    ...inv.post.map((file) => `- ${file}`),
    '',
    `## The renderer type named outside engine/render (${inv.renderer.length}; target 0)`,
    '',
    ...(inv.renderer.length > 0 ? inv.renderer.map((file) => `- ${file}`) : ['- none']),
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] === import.meta.filename) {
  const want = render(), path = join(ROOT, DOC);
  if (process.argv.includes('--check')) {
    const have = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (have !== want) { console.error(`${DOC} is stale: run node scripts/webgpu-inventory.mjs`); process.exitCode = 1; }
    else console.log(`${relative(ROOT, path)} is current`);
  } else { writeFileSync(path, want); console.log(`wrote ${DOC}`); }
}
