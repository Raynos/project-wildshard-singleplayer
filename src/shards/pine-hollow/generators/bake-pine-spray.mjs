#!/usr/bin/env node
// SHARD-PLATFORM W2: the waterfall's spray puffs baked offline (./sprayPuffs.ts) to src/shards/pine-hollow/data/sprayPuffs.json,
// which the page reads (src/shards/pine-hollow/runtime/world/streams.ts). `--check` refuses a stale file.
// Usage: node --experimental-transform-types --import ./scripts/bake-loader.mjs src/shards/pine-hollow/generators/bake-pine-spray.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { sprayPuffRows } from './sprayPuffs.ts';

const out = resolve(import.meta.dirname, '../data/sprayPuffs.json'), rows = sprayPuffRows();
const text = `${JSON.stringify({ notice: 'DO NOT EDIT: generated by generators/bake-pine-spray.mjs', ...rows })}\n`;
if (process.argv.includes('--check')) { if (!existsSync(out) || readFileSync(out, 'utf8') !== text) throw new Error('Pine spray puffs stale: run bake-pine-spray.mjs'); }
else writeFileSync(out, text);
console.info(`pine-hollow spray: ${String(rows.at.length / 3)} puffs`);
