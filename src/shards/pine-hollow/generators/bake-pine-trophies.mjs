#!/usr/bin/env node
// SHARD-PLATFORM W2: Pine Hollow's trophy-wall mounts baked offline (./trophyMounts.ts). Writes the geometry pack, zlib,
// hash-named and immutable, to public/assets/pine-hollow/baked/trophies-<sha12>.bin and its rows (url, byte size, hash,
// geometry rows, each mount slot's geometry) to src/shards/pine-hollow/data/trophyMounts.json, which the page
// reads (runtime/compendium/trophyWall.ts). `--check` refuses stale outputs.
// Usage: node --experimental-transform-types --import ./src/sdk/bake/source-loader.mjs src/shards/pine-hollow/generators/bake-pine-trophies.mjs
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { deflateSync } from 'node:zlib';
import { bakePineTrophies } from './trophyMounts.ts';

const root = resolve(import.meta.dirname, '../../../..'), check = process.argv.includes('--check');
const readAsset = url => Promise.resolve(new Uint8Array(readFileSync(resolve(root, `src/shards/pine-hollow/assets/creatures/${url.slice(url.lastIndexOf('/') + 1)}`))));
const { bin, rows, slots } = await bakePineTrophies(readAsset);
const sha256 = createHash('sha256').update(bin).digest('hex');
const url = `/assets/pine-hollow/baked/trophies-${sha256.slice(0, 12)}.bin`;
const packed = deflateSync(bin, { level: 9 });
const meta = `${JSON.stringify({ notice: 'DO NOT EDIT: generated by generators/bake-pine-trophies.mjs', url, sha256, rows, slots })}\n`;
const binPath = resolve(root, `public${url}`), metaPath = resolve(root, 'src/shards/pine-hollow/data/trophyMounts.json');
if (check) {
  if (!existsSync(binPath) || readFileSync(metaPath, 'utf8') !== meta) throw new Error('Pine trophy mounts stale: run bake-pine-trophies.mjs');
} else {
  mkdirSync(resolve(root, 'public/assets/pine-hollow/baked'), { recursive: true });
  writeFileSync(binPath, packed);
  writeFileSync(metaPath, meta);
}
console.info(`pine-hollow trophies: ${String(Object.keys(slots).length)} mounts, ${String(bin.length)} → ${String(packed.length)} zlib (${url})`);
