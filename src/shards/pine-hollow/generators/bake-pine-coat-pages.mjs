// Retained authoring producer. No page, renderer, live registry, runtime/ or legacy/ input is read.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { registerHooks } from 'node:module';
import { fileURLToPath } from 'node:url';

// Source TypeScript uses the same extensionless spelling as published SDK modules. This entry's resolver
// supplies only the missing extension; it does not install the game or synthesize renderer dependencies.
registerHooks({ resolve(specifier, context, next) {
  if (/^@wildshard\/(?:engine|game)\//u.test(specifier)) throw new Error('Pine coat producer cannot import a runtime');
  if (specifier.startsWith('.') && context.parentURL?.startsWith('file:')) {
    const at = new URL(specifier, context.parentURL);
    for (const suffix of ['', '.ts', '.mjs']) {
      const url = new URL(at.href + suffix);
      if (existsSync(fileURLToPath(url)) && statSync(fileURLToPath(url)).isFile()) return { url: url.href, shortCircuit: true };
    }
  }
  return next(specifier, context);
} });
const { producePineCoats } = await import('./coatProducer.ts');

const root = resolve(import.meta.dirname, '../../../..'), check = process.argv.includes('--check');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
/** @type {Record<string, Record<string, {image:string,sha256:string,pixels:string,width:number,height:number}>>} */
const tiers = {};
let count = 0;
for (const tier of ['phone', 'desktop']) {
  const products = await producePineCoats(url => {
    const asset = resolve(root, `src/shards/pine-hollow/assets/creatures/${url.slice(url.lastIndexOf('/') + 1)}`);
    const bytes = readFileSync(asset), destination = resolve(root, `public${url}`);
    if (check) {
      if (!existsSync(destination) || hash(readFileSync(destination)) !== hash(bytes)) throw new Error(`Pine rig asset stale: ${url}`);
    } else { mkdirSync(dirname(destination), {recursive: true}); writeFileSync(destination, bytes); }
    return Promise.resolve(new Uint8Array(bytes));
  }, /** @type {'phone'|'desktop'} */ (tier));
  const pages = {};
  for (const product of products) {
    const path = resolve(root, `public${product.image}`), sha256 = hash(product.png);
    if (check) {
      if (!existsSync(path) || hash(readFileSync(path)) !== sha256) throw new Error(`Pine coat page stale: ${product.image}`);
    } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, product.png); }
    pages[product.key] = { image: product.image, sha256, pixels: hash(product.pixels), width: product.width, height: product.height };
    count++;
  }
  tiers[tier] = pages;
}
const metadata = `${JSON.stringify({ notice: 'DO NOT EDIT: generated by generators/bake-pine-coat-pages.mjs from retained author recipes and GLB assets; regenerate and compare every raster hash.', tiers }, null, 2)}\n`;
const path = resolve(root, 'src/shards/pine-hollow/data/coatPages.generated.json');
if (check) { if (readFileSync(path, 'utf8') !== metadata) throw new Error('Pine coat page provenance stale'); }
else writeFileSync(path, metadata);
console.info(`Pine coat pages: ${count} authoring-only Node products${check ? ' match' : ' generated'}`);
