#!/usr/bin/env node
// SHARD-PLATFORM W2: Pine Hollow's code-built parts baked offline (./codeParts.ts): the hollow log, the token shelf, the
// stand-in people, the zipline trolley, the canoe, the zip-line cable and the cave's roof patch (over the terrain
// lattice, public/assets/baked/pine-hollow/terrain.bin). Writes the geometry pack, zlib, hash-named and immutable, to
// public/assets/pine-hollow/baked/code-parts-<sha12>.bin and its rows (url, hash, geometry rows, each part's geometry)
// to src/shards/pine-hollow/data/codeParts.json, which the page reads (src/shards/pine-hollow/runtime/world/codeParts.ts).
// `--check` refuses stale outputs.
// Usage: node --experimental-transform-types --import ./scripts/bake-loader.mjs src/shards/pine-hollow/generators/bake-pine-code-parts.mjs
import { hashImmutableBytes } from '@wildshard/sdk/immutable';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { encodeBuildBytes } from '@wildshard/sdk/bake/byteCodec';
import { readNativeTerrain } from '@wildshard/sdk/bake/terrain';
import { bakePineCodeParts, hollowLogColliders } from './codeParts.ts';
import { pineScriptSources } from './scriptSources.mjs';
import { timberWorld } from './timberWorldRows.ts';

const root = resolve(import.meta.dirname, '../../../..'), check = process.argv.includes('--check');
const ground = readNativeTerrain(readFileSync(resolve(root, 'public/assets/baked/pine-hollow/terrain.bin')));
const pickups=JSON.parse(readFileSync(resolve(root,'src/game/data/pickupCatalogue.json'),'utf8'));
const pickupFiles=new Map(pickups.geometries.flatMap(row=>{
  if(!('file'in row))return [];
  if(!/^\/assets\/baked\/common\/pickups\/[a-f0-9]{64}\.bin$/u.test(row.file))throw new Error('Invalid prepared pickup source');
  return [[row.file,new Uint8Array(readFileSync(resolve(root,`public${row.file}`)))]];
}));
// GR8 G37: the zip line and cave roof rows are the program's timber world
const { bin, rows, parts } = bakePineCodeParts(ground.heightAt,timberWorld(await pineScriptSources('pine-code-parts')),pickupFiles);
const sha256 = hashImmutableBytes(bin);
const url = `/assets/pine-hollow/baked/code-parts-${sha256.slice(0, 12)}.bin`;
const packed = encodeBuildBytes(bin, 'deflate', 9, 'native');
const meta = `${JSON.stringify({ notice: 'DO NOT EDIT: generated by generators/bake-pine-code-parts.mjs', url, sha256, rows, parts, colliders: { 'hollow-log': hollowLogColliders() } })}\n`;
const binPath = resolve(root, `public${url}`), metaPath = resolve(root, 'src/shards/pine-hollow/data/codeParts.json');
if (check) {
  if (!existsSync(binPath) || !existsSync(metaPath) || readFileSync(metaPath, 'utf8') !== meta) throw new Error('Pine code parts stale: run bake-pine-code-parts.mjs');
} else {
  mkdirSync(resolve(root, 'public/assets/pine-hollow/baked'), { recursive: true });
  writeFileSync(binPath, packed);
  writeFileSync(metaPath, meta);
}
console.info(`pine-hollow code parts: ${String(Object.keys(parts).length)} parts, ${String(bin.length)} → ${String(packed.length)} zlib (${url})`);
