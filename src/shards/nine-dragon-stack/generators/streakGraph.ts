import type { GraphIr } from '@wildshard/format/materialGraph';
import { LookGraph } from './lookGraph';
import fog from '../data/lookGraphs.json' with { type: 'json' };

/** Mirror each emitter's extent in its receiver plane; dash and grain remain world anchored. */
export function streakGraph(): GraphIr {
  const g = new LookGraph();
  const op = g.op.bind(g);
  const sw = g.sw.bind(g);
  const add = g.add.bind(g);
  const sub = g.sub.bind(g);
  const mul = g.mul.bind(g);
  const div = g.div.bind(g);
  const max = g.max.bind(g);
  const min = g.min.bind(g);
  const mix = g.mix.bind(g);
  const smooth = g.smooth.bind(g);
  const clamp = g.clamp.bind(g);
  const v = g.v.bind(g);
  const vec = g.vec.bind(g);
  const noise = g.noise.bind(g);
  const root = g.p('rootAt', 'vec3', [0, 0, 0]);
  const origin = g.a('aPlaneO', 'vec3'), u = g.a('aPlaneU', 'vec3'), n = g.a('aPlaneN', 'vec3'), z = op('cross', [u, n]);
  const toPlane = (p: string): string => { const q = sub(p, origin); return vec(op('dot', [q, u]), op('dot', [q, n]), op('dot', [q, z])); };
  const fromPlane = (p: string): string => add(origin, add(add(mul(u, sw(p, 'x')), mul(n, sw(p, 'y'))), mul(z, sw(p, 'z'))));
  const cam = sub(op('cameraPosition'), root), eye = toPlane(cam), emitter = g.a('aE', 'vec3'), e = toPlane(emitter);
  const size = g.a('aSize', 'vec3'), corner = g.a('aCorner', 'vec2'), spread = g.a('aSpread', 'vec4'), k = g.a('aCardK', 'vec4');
  const c = max(sw(eye, 'y'), 0.05), hb = max(sub(sw(e, 'y'), mul(sw(size, 'y'), 0.5)), 0.05), ht = max(add(sw(e, 'y'), mul(sw(size, 'y'), 0.5)), add(hb, 0.05));
  const delta = sub(sw(e, 'xz'), sw(eye, 'xz')), distance = max(op('length', [delta]), 0.1), dir = div(delta, distance);
  const sn = div(mul(distance, c), add(c, ht)), sf = div(mul(distance, c), add(c, hb)), sm = div(mul(distance, c), add(c, mul(add(hb, ht), 0.5)));
  const forward = op('viewToWorld', [[0, 0, -1]]), fw = vec(op('dot', [forward, u]), op('dot', [forward, n]), op('dot', [forward, z]));
  const down = smooth(0.45, 0.85, mul(sw(fw, 'y'), -1)), steep = smooth(0.25, 0.9, div(c, distance));
  const tail = mul(sub(1, mul(steep, 0.4)), sub(1, mul(down, 0.75)));
  const color = g.a('aCol', 'vec3'), warm = add(1, mul(1.5, clamp(div(sub(sw(color, 'x'), sw(color, 'z')), max(sw(color, 'x'), 1e-3)))));
  const rawCol = mul(mul(mul(color, sw(size, 'z')), warm), mul(op('step', [-0.5, sw(eye, 'y')]), op('step', [0.2, sw(e, 'y')])));
  const projection = g.p('projection', 'vec2', [1, 1]), right = op('viewToWorld', [[1, 0, 0]]), up = op('viewToWorld', [[0, 1, 0]]);
  const relative = sub(add(emitter, root), op('cameraPosition')), depth = op('dot', [relative, forward]);
  const ndc = div(mul(vec(op('dot', [relative, right]), op('dot', [relative, up])), projection), max(depth, 1e-4));
  const onScreen = mul(op('step', [0, depth]), sub(1, smooth(0.8, 1, max(op('abs', [sw(ndc, 'x')]), op('abs', [sw(ndc, 'y')])))));
  const screenGain = mix(1, g.p('cardOn', 'float', 1), onScreen);
  const col = mul(rawCol, screenGain);
  const perf = g.p('perf', 'vec4', [2.5, 0.3, 0, 0]), gm = mul(max(sw(col, 'x'), max(sw(col, 'y'), sw(col, 'z'))), sw(k, 'x'));
  const tailK = op('select', [op('gt', [sw(perf, 'x'), 0]), clamp(div(gm, sw(perf, 'x')), 0.15, 1), 1]);
  const s0 = mix(sn, sw(spread, 'w'), clamp(mul(mul(sw(spread, 'x'), tail), tailK))), s1 = mix(sf, distance, clamp(mul(sw(spread, 'y'), tail)));
  const fwXZ = op('select', [op('gt', [op('length', [sw(fw, 'xz')]), 1e-3]), op('normalize', [sw(fw, 'xz')]), dir]);
  const sign = op('select', [op('gte', [add(op('dot', [fwXZ, dir]), 1e-3), 0]), 1, -1]);
  const axis = op('normalize', [mix(dir, mul(fwXZ, sign), down)]), side = vec(mul(sw(axis, 'y'), -1), sw(axis, 'x'));
  const s = mix(s0, s1, sw(corner, 'y')), wk = mul(div(mul(sw(size, 'x'), 0.5), distance), sw(spread, 'z'));
  const halfWidth = mul(add(mul(wk, s), 0.01), add(1, mul(steep, 0.5)));
  const xz = add(add(add(sw(eye, 'xz'), mul(dir, sm)), mul(axis, sub(s, sm))), mul(side, mul(sw(corner, 'x'), halfWidth)));
  const wp = fromPlane(vec(sw(xz, 'x'), add(0.004, mul(g.a('aLift', 'float'), down)), sw(xz, 'y')));
  const world = add(wp, root), fogT = g.fog(fog['nine-silk-fog'], world), transmission = v(fogT);
  const position = op('select', [op('lt', [gm, sw(perf, 'y')]), [1e6, 1e6, 1e6], op('worldToLocal', [sub(world, op('objectOrigin'))])]);
  const p = sw(v(wp), 'xz'), seg = v(vec(s0, sn, sf, s1)), vs = v(s), vc = v(corner), vd = v(down), vk = v(k);
  const body = op('select', [op('lt', [vs, sw(seg, 'y')]), div(sub(vs, sw(seg, 'y')), max(sub(sw(seg, 'y'), sw(seg, 'x')), 1e-3)), op('select', [op('lt', [vs, sw(seg, 'z')]), div(sub(vs, sw(seg, 'y')), max(sub(sw(seg, 'z'), sw(seg, 'y')), 1e-3)), add(1, div(sub(vs, sw(seg, 'z')), max(sub(sw(seg, 'w'), sw(seg, 'z')), 1e-3)))])]);
  const profile = op('select', [op('lt', [body, 0]), op('pow', [clamp(add(1, body)), 1.4]), op('select', [op('gt', [body, 1]), op('pow', [clamp(sub(2, body)), 2]), 1])]);
  const along = op('dot', [sub(p, sw(cam, 'xz')), v(axis)]), time = g.p('time', 'float', 0);
  const cb = op('floor', [div(add(mul(p, 0.7), 37), [1.1, 0.62])]), seed = g.hash(add(cb, 17));
  const footprint = max(op('fwidth', [along]), 1e-5);
  const ripple = (frequency: number, across: number, speed: number): string => sub(noise(vec(mul(along, frequency), add(mul(sw(vc, 'x'), across), mul(time, speed)))), 0.5);
  const fine = add(add(mul(mul(ripple(38, 0.7, 0.9), 2), sub(1, smooth(0.009, 0.022, footprint))), mul(mul(ripple(95, 1.3, -1.3), 1.4), sub(1, smooth(0.0035, 0.009, footprint)))), mul(mul(ripple(14, 0.5, 0.6), 1.2), smooth(0.012, 0.03, footprint)));
  const jog = mul(mul(sub(mul(g.hash(cb), 2), 1), sw(vk, 'z')), 0.5);
  const x = add(add(add(sw(vc, 'x'), jog), mul(sub(noise(vec(mul(along, 2.5), mul(time, 0.5))), 0.5), 0.3)), mul(mul(fine, 0.4), sub(1, mul(vd, 0.8))));
  const across = sub(1, smooth(mix(0.5, 0.15, vd), 1, op('abs', [x])));
  const stria = add(0.7, mul(noise(vec(add(mul(sw(vc, 'x'), 11), mul(seed, 5)), mul(along, 1.5))), 0.3));
  const dash = mul(mul(mix(1, smooth(0.15, 0.75, noise(vec(mul(along, 17), add(mul(x, 2.5), mul(seed, 9))))), mul(sw(vk, 'y'), sub(1, mul(vd, 0.7)))), stria), add(0.72, mul(noise(mul(p, 97)), 0.28)));
  const view = op('normalize', [sub(cam, v(wp))]), fresnel = add(0.3, mul(op('pow', [clamp(sub(1, op('dot', [view, v(n)]))), 3]), 0.7));
  const course = op('floor', [div(sw(p, 'y'), 0.62)]);
  const h11 = (input: string): string => op('fract', [mul(op('sin', [mul(input, 127.1)]), 43758.5453123)]);
  const length = add(0.64, mul(h11(add(mul(course, 9.1), 2)), 0.28)), offset = mul(h11(mul(course, 3.7)), 1.1);
  const cx = op('floor', [div(add(sw(p, 'x'), offset), length)]), local = vec(sub(add(sw(p, 'x'), offset), mul(cx, length)), sub(sw(p, 'y'), mul(course, 0.62)));
  const pixelWidth = max(op('fwidth', [p]), [1e-5, 1e-5]), lw = max(min(mul(pixelWidth, 1.1), [0.012, 0.012]), g.p('flagJoint', 'float', 0.004));
  const dimensions = vec(length, 0.62), joints = div(local, dimensions), edge = mul(min(joints, sub(1, joints)), dimensions);
  const lines = mul(sub(1, smooth(lw, add(lw, pixelWidth), edge)), smooth(4, 9, div(dimensions, pixelWidth)));
  const joint = max(sw(lines, 'x'), sw(lines, 'y'));
  const puddle = smooth(0.42, 0.72, add(mul(noise(add(mul(p, 0.21), 3)), 0.6), mul(noise(mul(p, 0.83)), 0.4)));
  const gloss = mul(mix(0.45, 1, puddle), add(0.65, mul(seed, 0.7)));
  const intensity = mul(mul(mul(mul(mul(mul(profile, across), dash), gloss), fresnel), sub(1, mul(joint, 0.8))), sw(vk, 'x'));
  let out = mul(mul(v(col), intensity), transmission);
  const peak = max(sw(out, 'x'), max(sw(out, 'y'), sw(out, 'z')));
  out = mix(out, mul(div(out, max(peak, 1e-4)), min(peak, 1)), mul(sw(vk, 'w'), op('step', [1, peak])));
  const clip = v(g.a('aClip', 'vec4')), hole = v(g.a('aHole', 'vec4'));
  const inside = (r: string): string => op('and', [op('and', [op('gt', [sw(p, 'x'), sw(r, 'x')]), op('lt', [sw(p, 'x'), sw(r, 'z')])]), op('and', [op('gt', [sw(p, 'y'), sw(r, 'y')]), op('lt', [sw(p, 'y'), sw(r, 'w')])])]);
  const discard = op('or', [inside(hole), op('or', [op('not', [inside(clip)]), op('lt', [v(gm), sw(perf, 'y')])])]);
  return g.finish({ 'vertex.position': { position }, surface: { colour: out, alpha: 1, discard } });
}
