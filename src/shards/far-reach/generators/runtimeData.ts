import { SKY_RUNTIME_ROWS } from './rows/runtimeRows';
import { GEAR_SCENE_ROWS } from './rows/gearModels';

/** Reflect the checked data's tuple and literal types at the JSON import boundary. */
function shape(value: unknown): string {
  if (value === null) return 'null';
  if (typeof value === 'number') return 'number';
  if (typeof value === 'string' || typeof value === 'boolean') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(shape).join(',')}]`;
  if (typeof value === 'object') return `{${Object.entries(value).map(([key, entry]) => `${JSON.stringify(key)}:${shape(entry)}`).join(';')}}`;
  throw new Error('Runtime rows must be JSON data');
}

/** Emit the build-checked rows consumed by the existing hybrid page host. */
export function runtimeData(): ReadonlyMap<string, Uint8Array> {
  return new Map(Object.entries({ 'runtimeRows': SKY_RUNTIME_ROWS, 'gearRows': GEAR_SCENE_ROWS }).flatMap(([name, rows]) => [
    [`data/${name}.generated.json`, new TextEncoder().encode(`${JSON.stringify(rows)}\n`)],
    [`data/${name}.generated.d.json.ts`, new TextEncoder().encode(`// Generated by generators/runtimeData.ts.\ndeclare const rows: ${shape(rows)};\nexport default rows;\n`)],
  ]));
}
