import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { nalatiSpecimenRows } from './specimenRows.ts';
import { byteWriter, jsonBytes } from '../../../../scripts/bake-output.mjs';

const root = new URL('../', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(`data/${name}.json`, root), 'utf8'));
const writer = byteWriter(process.argv.includes('--check'), 'camp-specimens');
const rows = nalatiSpecimenRows(read('campCatalogue'), read('campMaterials'), read('placeSpecimens'));
// Build-time data: generators read it, play code reads its product rows (never author imports).
writer.put(fileURLToPath(new URL('data/specimens.generated.json', root)), jsonBytes(rows));
writer.put(fileURLToPath(new URL('boot/specimenParams.generated.d.ts', root)), new TextEncoder().encode(`// Generated by generators/bake-specimens.mjs. Edit generators/campParams.ts.\n${readFileSync(new URL('generators/campParams.ts', root), 'utf8')}`));
writer.put(fileURLToPath(new URL('data/specimens.generated.d.json.ts', root)), new TextEncoder().encode("import type { SpecimenBindings } from './specimenBindings';\ndeclare const rows: SpecimenBindings;\nexport default rows;\n"));
writer.finish();
