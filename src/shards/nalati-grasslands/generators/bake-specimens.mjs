import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { byteWriter, jsonBytes } from '../../../../scripts/bake-output.mjs';

const root = new URL('../', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(`data/${name}.json`, root), 'utf8'));
const writer = byteWriter(process.argv.includes('--check'), 'camp-specimens');
const rows = { catalogue: read('campCatalogue'), materials: read('campMaterials'), packed: { ...read('placeSpecimens'), bin: '/assets/nalati/baked/specimens.bin' } };
// Asset identities and material settings are authored once; runtime borrowers use the specimen host directly.
rows.assets = Object.fromEntries(rows.catalogue.filter(row => row.source.kind === 'asset').map(row => [row.key, row.source.asset]));
for (const name of ['boulder-1', 'boulder-2', 'boulder-3', 'balbal']) {
  const rim = name === 'balbal' ? .35 : .3;
  rows.assets[name] = { url: `/assets/nalati/baked/painted-models/${name}.glb`, phoneUrl: `/assets/nalati/baked/painted-models/${name}.phone.glb`,
    geometrySlot: 0, materialSlot: 0, retainedAttribute: '_paint_clone', material: { id: `nalati-model:${name}|near|${rim}|0.8||ffffff`, family: 'painterly', rim, bands: .8, floor: .2 } };
}
rows.assets.kokparRiderFar = { ...rows.assets.kokparRider, url: '/assets/nalati/baked/painted-models/kokpar-rider.far.glb', phoneUrl: '/assets/nalati/baked/painted-models/kokpar-rider.far.glb',
  material: { ...rows.assets.kokparRider.material, id: 'nalati-model:kokpar-rider|far|0.8|0.85||ffffff' } };
// Pre-admission model registration needs generated boot metadata, never author imports.
writer.put(fileURLToPath(new URL('boot/specimens.generated.json', root)), jsonBytes(rows));
writer.put(fileURLToPath(new URL('boot/specimenParams.generated.d.ts', root)), new TextEncoder().encode(`// Generated by generators/bake-specimens.mjs. Edit generators/campParams.ts.\n${readFileSync(new URL('generators/campParams.ts', root), 'utf8')}`));
writer.put(fileURLToPath(new URL('boot/specimens.generated.d.json.ts', root)), new TextEncoder().encode("import type { SpecimenBindings } from '../data/specimenBindings';\ndeclare const rows: SpecimenBindings;\nexport default rows;\n"));
writer.finish();
