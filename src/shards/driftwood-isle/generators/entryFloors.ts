import { Group } from 'three';
import { BoxCollider, type BoxColliderData } from '@wildshard/sdk/physics';
import { readScene } from '@wildshard/sdk/scene';
import { CHUNK_HALF, ENTRY_ASPHALT, ENTRY_WIDTH } from '@wildshard/format/contentBounds';
import { DRY_ENTRIES, LANDING_RUN, LANDING_HALF, type DryEntryEdge } from '../data/entryRows';

/** The primitive floor product; its notice and every box survive persisted JSON. */
export interface DriftwoodEntryFloorProduct {
  notice: string;
  rows: { edge: DryEntryEdge; box: BoxColliderData }[];
}

/** The four original landing slabs as ordinary SDK collider objects, at road height. */
export function driftwoodEntryFloorScene(): Group {
  const scene = new Group(); scene.name = 'driftwood.entry-landings';
  const centre = CHUNK_HALF - ENTRY_ASPHALT - LANDING_RUN / 2;
  const across = ENTRY_WIDTH / 2, along = LANDING_RUN / 2;
  const at = { north: [0, centre, across, along], south: [0, -centre, across, along],
    east: [centre, 0, along, across], west: [-centre, 0, along, across] } as const;
  for (const edge of DRY_ENTRIES) {
    const [x, z, hx, hz] = at[edge];
    const box = new BoxCollider(hx * 2, LANDING_HALF * 2, hz * 2, 'stone');
    box.name = edge; box.position.set(x, -LANDING_HALF, z); scene.add(box);
  }
  return scene;
}

/** Compile retained SDK objects to data; no scene, level or native registry is installed. */
export function driftwoodEntryFloorRows(): DriftwoodEntryFloorProduct {
  const compiled = readScene(driftwoodEntryFloorScene());
  return { notice: 'DO NOT EDIT: generated by driftwood-entry-floors through the verified build cache.',
    rows: DRY_ENTRIES.map(edge => {
      const box = compiled.colliders.find(row => row.id === edge)?.shape;
      if (box?.kind !== 'box' || box.surface !== 'stone') throw new Error(`Missing authored entry floor ${edge}`);
      return { edge, box };
    }) };
}
