import { siteCatalogue } from './siteCatalogue.ts';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { byteWriter, jsonBytes } from '../../../../scripts/bake-output.mjs';

const root = new URL('../', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(`data/${name}.json`, root), 'utf8'));
const writer = byteWriter(process.argv.includes('--check'), 'trail-specimens');
const rows = { catalogue: read('trailCatalogue'), siteCatalogue: siteCatalogue() };
// Pre-admission model registration needs generated boot metadata, never author imports.
writer.put(fileURLToPath(new URL('boot/modelCatalogue.generated.json', root)), jsonBytes(rows));
writer.put(fileURLToPath(new URL('boot/specimenParams.generated.d.ts', root)), new TextEncoder().encode(`// Generated by generators/bake-specimens.mjs. Edit generators/trailParams.ts.\n${readFileSync(new URL('generators/trailParams.ts', root), 'utf8')}`));
writer.finish();
