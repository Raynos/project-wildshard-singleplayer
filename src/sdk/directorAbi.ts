import { parseDirector } from '@wildshard/format/director';
import { parseDirectorStages } from '@wildshard/format/directorStages';

const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const reserved = new Set(['true', 'false', 'null', 'constructor', 'prototype', '__proto__', 'new', 'return', 'class', 'static', 'get', 'set', 'export', 'import', 'default', 'extends', 'implements', 'private', 'public', 'protected', 'this', 'super', 'if', 'else', 'for', 'while', 'switch', 'case', 'break', 'continue', 'function', 'let', 'const', 'var', 'void', 'type', 'interface', 'namespace', 'enum', 'try', 'catch', 'throw']);
function camel(key: string): string { return key.replaceAll(/[.-]([a-z0-9])/gu, (_match: string, letter: string) => letter.toUpperCase()); }
/** Generate readable, allocation-free AssemblyScript accessors from admitted v1 numeric or v2 boolean director inputs.
 * v1 inputs remain f64 even at bounds 0..1: a bounded channel is not implicitly a boolean (night can be fractional).
 * Input aliases use camelCase; collisions and reserved words refuse before compilation.
 * Clock and incomingEvents expose the unchanged ABI-v0 host channels. */
export function generateDirectorAbi(input: unknown): string {
  const boolean = typeof input === 'object' && input !== null && 'version' in input && input.version === 2;
  const names = boolean ? Object.keys(parseDirectorStages(input).inputs) : parseDirector(input).inputs.map(row => camel(row.key));
  if (names.some(name => name.length > 128 || !identifier.test(name) || reserved.has(name)) || new Set(names).size !== names.length) throw new Error('Director ABI names must be unique AssemblyScript identifiers');
  const getter = (name: string, address: number): string => `  @inline static get ${name}(): f64 { return load<f64>(${address}); }`;
  return [
    '// DO-NOT-EDIT: generated by @wildshard/sdk/directorAbi from the admitted director declaration.',
    '// ABI v0: the host validates observations, event counts and parameter values before this module runs.',
    'export class inputs {', ...names.map((name, index) => boolean
      ? `  @inline static get ${name}(): bool { return load<f64>(${16384 + (6 + index) * 8}) === 1; }`
      : getter(name, 16384 + (6 + index) * 8)), '}',
    'export class clock {', getter('tick', 16384), getter('dt', 16392), getter('self', 16408), '}',
    'export class incomingEvents {',
    '  @inline static get count(): i32 { return i32(load<f64>(16640)); }',
    '  @inline static type(index: i32): f64 { return load<f64>(16648 + index * 48); }', '}',
  ].join('\n');
}
