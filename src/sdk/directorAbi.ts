import { parseDirector } from '@wildshard/format/director';
import { parseDirectorStages } from '@wildshard/format/directorStages';
import { StateSchema } from '@wildshard/format/state';
import * as v from 'valibot';

const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const reserved = new Set(['true', 'false', 'null', 'constructor', 'prototype', '__proto__', 'new', 'return', 'class', 'static', 'get', 'set', 'export', 'import', 'default', 'extends', 'implements', 'private', 'public', 'protected', 'this', 'super', 'if', 'else', 'for', 'while', 'switch', 'case', 'break', 'continue', 'function', 'let', 'const', 'var', 'void', 'type', 'interface', 'namespace', 'enum', 'try', 'catch', 'throw']);
function camel(key: string): string { return key.replaceAll(/[.-]([a-z0-9])/gu, (_match: string, letter: string) => letter.toUpperCase()); }
/** Generate readable, allocation-free AssemblyScript accessors from admitted v1 numeric or v2 boolean director inputs.
 * v1 inputs remain f64 even at bounds 0..1: a bounded channel is not implicitly a boolean (night can be fractional).
 * Input aliases use camelCase; collisions and reserved words refuse before compilation.
 * Clock and incomingEvents expose the unchanged ABI-v0 host channels. */
export function generateDirectorAbi(input: unknown): string {
  const boolean = typeof input === 'object' && input !== null && 'version' in input && input.version === 2;
  const names = boolean ? Object.keys(parseDirectorStages(input).inputs) : parseDirector(input).inputs.map(row => camel(row.key));
  if (names.some(name => name.length > 128 || !identifier.test(name) || reserved.has(name)) || new Set(names).size !== names.length) throw new Error('Director ABI names must be unique AssemblyScript identifiers');
  const getter = (name: string, address: number): string => `  @inline static get ${name}(): f64 { return load<f64>(${address}); }`;
  return [
    '// DO-NOT-EDIT: generated by @wildshard/sdk/directorAbi from the admitted director declaration.',
    '// ABI v0: the host validates observations, event counts and parameter values before this module runs.',
    'export class inputs {', ...names.map((name, index) => boolean
      ? `  @inline static get ${name}(): bool { return load<f64>(${16384 + (6 + index) * 8}) === 1; }`
      : getter(name, 16384 + (6 + index) * 8)), '}',
    'export class clock {', getter('tick', 16384), getter('dt', 16392), getter('self', 16408), '}',
    'export class incomingEvents {',
    '  @inline static get count(): i32 { return i32(load<f64>(16640)); }',
    '  @inline static type(index: i32): f64 { return load<f64>(16648 + index * 48); }', '}',
  ].join('\n');
}

/** An executable numeric ABI-v0 module and its exact byte/record layout, generated from admitted state rows. */
export interface GeneratedScriptModule {
  source: string;
  layout: { version: 0; inputBytes: number; outputRecords: number; outputBytes: number; eventCountOffset: 256; eventOffset: 264; eventStride: 48; effectStride: 40; minimumPages: 1 };
}

/** Generate a complete typed AS handler: host exports, allocated buffers, clocks, events and actor-scoped state effects.
 * Capacities are bytes for in_cap and five-f64 records for out_cap. Native actor binding is never authored here.
 * State getters follow stable field-ID order; strings have no numeric ABI and refuse. The handler is the on_tick body. */
export function generateScriptModule(state: unknown, handler: string, options: { events?: number; effects?: number } = {}): GeneratedScriptModule {
  const row = v.parse(StateSchema, state), events = options.events ?? 32, effects = options.effects ?? 8;
  if (!Number.isInteger(events) || events < 0 || events > 32 || !Number.isInteger(effects) || effects < 1 || effects > 128) throw new Error('ABI event/effect capacity outside host limits');
  if ([...row.shared, ...row.player].some(field => field.type === 'string')) throw new Error('Strings have no numeric script ABI');
  const shared = [...row.shared].sort((a, b) => a.id - b.id), player = [...row.player].sort((a, b) => a.id - b.id);
  const fields = (list: typeof shared, start: number, operation: number): string[] => {
    const names = list.map(field => camel(field.name));
    if (names.some(name => !identifier.test(name) || reserved.has(name)) || new Set(names).size !== names.length) throw new Error('State ABI aliases must be unique AssemblyScript identifiers');
    return list.flatMap((field, index) => {
      const name = names[index], type = field.type === 'bool' ? 'bool' : field.type;
      if (name === undefined) throw new Error('Missing state ABI alias');
      const read = `load<f64>(INPUT + ${8 * (start + index)})`;
      return [`  @inline static get ${name}(): ${type} { return ${type === 'bool' ? `${read} === 1` : `${type}(${read})`}; }`,
        `  @inline static set ${name}(value: ${type}) { ${operation === 6 ? 'assert(clock.actorToken > 0); ' : ''}effects.write(${operation}, ${field.id}, f64(value), 0, 0); }`];
    });
  };
  const inputBytes = 264 + events * 48, outputBytes = effects * 40;
  const source = [
    '// DO-NOT-EDIT: generated by @wildshard/sdk/directorAbi#generateScriptModule from admitted state rows.',
    '// ABI v0: in_cap is BYTES; out_cap is RECORDS. Host-owned actor provenance cannot be supplied by an effect.',
    `const INPUT: usize = memory.data(${inputBytes});`, `const OUTPUT: usize = memory.data(${outputBytes});`, 'let count: i32 = 0;',
    'export function abi_version(): i32 { return 0; }', 'export function init(seedLo: i32, seedHi: i32): void {}',
    'export function in_ptr(): i32 { return i32(INPUT); }', `export function in_cap(): i32 { return ${inputBytes}; }`,
    'export function out_ptr(): i32 { return i32(OUTPUT); }', `export function out_cap(): i32 { return ${effects}; }`,
    'export function out_count(): i32 { return count; }',
    'class clock {',
    ...['tick', 'dt', 'command', 'self', 'actorToken', 'role', 'sharedCount', 'playerCount'].map((name, index) => `  @inline static get ${name}(): f64 { return load<f64>(INPUT + ${index * 8}); }`), '}',
    'class incomingEvents {', '  @inline static get count(): i32 { return i32(load<f64>(INPUT + 256)); }',
    ...['type', 'target', 'value'].map((name, index) => `  @inline static ${name}(index: i32): f64 { assert(index >= 0 && index < incomingEvents.count); return load<f64>(INPUT + 264 + usize(index) * 48 + ${index * 8}); }`), '}',
    'class effects {', '  @inline static write(op: f64, a: f64, b: f64, c: f64, d: f64): void {',
    `    assert(count < ${effects}); const at = OUTPUT + usize(count++) * 40;`,
    ...['op', 'a', 'b', 'c', 'd'].map((name, index) => `    store<f64>(at + ${index * 8}, ${name});`), '  }',
    '  @inline static event(type: i32, target: i32, value: f64): void { effects.write(3, type, target, value, 0); }', '}',
    'class shared {', ...fields(shared, 8, 5), '}', 'class player {', ...fields(player, 8 + shared.length, 6), '}',
    'export function on_tick(): void { count = 0;', handler, '}', '',
  ].join('\n');
  return { source, layout: { version: 0, inputBytes, outputRecords: effects, outputBytes, eventCountOffset: 256, eventOffset: 264, eventStride: 48, effectStride: 40, minimumPages: 1 } };
}
