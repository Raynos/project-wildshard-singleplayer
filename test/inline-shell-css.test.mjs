import { expect, test } from 'vitest';
// oxlint-disable-next-line import/no-nodejs-modules -- The check reads the committed document and the two stylesheets it copies.
import { readFileSync } from 'node:fs';
import { inlineShellCss } from '../scripts/inline-shell-css.mjs';

test('index.html paints the loading card with its own stylesheets from the first frame (DL21)', () => {
  const html = readFileSync('index.html', 'utf8');
  // a drifted copy (base.css or loading.css edited without rerunning the script) refuses here
  expect(inlineShellCss(html)).toBe(html);
  // the cut-down shell rules are gone: their higher specificity kept the 3 s card half-styled on Jake's phone
  expect(html).not.toMatch(/\.ws-load\[data-shell\] \./u);
});

test('the block is replaced in place and refuses a document without exactly one', () => {
  const read = (path) => (path.endsWith('base.css') ? ':root { --a: 1; }' : '.ws-load { color: red; }');
  const open = '/* <inline-shell-css> generated by scripts/inline-shell-css.mjs from base.css + loading.css: do not edit */', close = '/* </inline-shell-css> */';
  expect(inlineShellCss(`<style>${open}old${close}x</style>`, read)).toBe(`<style>${open}\n:root { --a: 1; }\n.ws-load { color: red; }\n${close}x</style>`);
  expect(() => inlineShellCss('<style></style>', read)).toThrow(/exactly one/u);
});
