function program(graph: GraphIr, fog: THREE.Fog): THREE.WebGLProgramParametersWithUniforms {
  const renderer: unknown = Object.create(THREE.WebGLRenderer.prototype);
  if (!(renderer instanceof THREE.WebGLRenderer)) throw new Error('Missing renderer');
  const fields: Record<string, unknown> = {
    extensions: { has: () => false, get: () => null }, getContext: () => ({}), getRenderTarget: () => null,
    toneMapping: THREE.ACESFilmicToneMapping, toneMappingExposure: 1, outputColorSpace: THREE.SRGBColorSpace,
    coordinateSystem: THREE.WebGLCoordinateSystem, info: { render: { frame: 0 } },
    debug: { checkShaderErrors: true, diagnostics: { keywords: false } }, properties: { get: () => ({}), has: () => false },
  };
  for (const [key, value] of Object.entries(fields)) Reflect.set(renderer, key, value);
  const sampled = new THREE.DataTexture(new Uint8Array([255, 255, 255, 255]), 1, 1);
  const handler = new EngineNodesHandler(), material = compileGraph(graph, { textures: () => sampled }).material;
  handler.setRenderer(renderer);
  const geometry = new THREE.PlaneGeometry(1, 1); geometry.setAttribute('aSeed', new THREE.Float32BufferAttribute([0, 0.25, 0.5, 0.75], 1));
  geometry.setAttribute('aDirection', new THREE.Float32BufferAttribute([1, 1, 0, 1, 1, 0, 1, 1, 0, 1, 1, 0], 3));
  const object = new THREE.Mesh(geometry, material);
  const scene = new THREE.Scene(), camera = new THREE.PerspectiveCamera();
  scene.fog = fog; scene.add(object); handler.renderStart(scene, camera); handler.updateLights([]);
  const parameters: object = {};
  const isParameters = (value: object): value is THREE.WebGLProgramParametersWithUniforms => !Array.isArray(value);
  if (!isParameters(parameters)) throw new Error('Missing parameters');
  try { handler.build(material, object, parameters); return parameters; }
  finally { geometry.dispose(); material.dispose(); sampled.dispose(); }
}


test('fogColour borrows the current scene colour and follows its live updates', () => {
  const fog = new THREE.Fog(0x123456, 1, 100);
  const graph: GraphIr = { version: 1, kind: 'material', model: 'unlit',
    nodes: { fog: { op: 'fogColour' } }, stages: { surface: { colour: 'fog' } } };
  const shader = program(graph, fog);
  const uniform = Object.values(shader.uniforms).find(value => value.value === fog.color);
  if (uniform === undefined) throw new Error('Fog colour was not borrowed');
  fog.color.set(0xabcdef);
  expect(uniform.value).toBe(fog.color);
  expect(validateGraph(graph).ok).toBe(true);
  expect(validateGraph({ ...graph, stages: { 'vertex.offset': { offset: 'fog' }, surface: { colour: 'fog' } } }).ok).toBe(true);
});
